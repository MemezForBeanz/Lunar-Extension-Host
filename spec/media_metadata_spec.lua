package.path = "./extensions/media-server/?.lua;" .. package.path
local tmdb = require("libs.tmdb")
local Metadata = require("libs.metadata")
local Catalog = require("libs.catalog")
local schema = require("libs.schema")
local sqlite = require("core.lib.sqlite")
local cjson = require("cjson")
local platform = require("core.platform")

local details = { id = 597, title = "Titanic", release_date = "1997-11-18", overview = "A voyage.",
	vote_average = 7.9, poster_path = "/poster.jpg", backdrop_path = "/wide.jpg",
	genres = { { name = "Drama" } }, production_companies = { { name = "Studio" } },
	credits = { cast = { { name = "Actor", character = "Passenger", profile_path = "/face.jpg" } } } }
local function detailBody(extra)
	local copy = {}; for k, v in pairs(details) do copy[k] = v end
	for k, v in pairs(extra or {}) do copy[k] = v end
	return cjson.encode(copy)
end

describe("TMDB metadata mapping", function()
	it("matches one exact title and release year instead of popularity", function()
		local results = { { id = 1, title = "Titanic", year = 1953 }, { id = 597, title = "Titanic", year = 1997 } }
		assert.equal(597, tmdb.pick({ title = "Titanic", year = 1997 }, results).id)
		assert.is_nil(tmdb.pick({ title = "Titanic" }, results))
		assert.is_nil(tmdb.pick({ title = "Titanic", year = 1998 }, results))
	end)
	it("accepts original titles, but not fuzzy unrelated titles", function()
		assert.equal(1, tmdb.pick({ title = "Le Film", year = 2000 }, { { id = 1, title = "The Film", original_title = "Le Film", year = 2000 } }).id)
		assert.is_nil(tmdb.pick({ title = "Film", year = 2000 }, { { id = 1, title = "The Film", year = 2000 } }))
	end)
	it("maps proper posters, backdrops, cast and descriptive facts", function()
		local facts = assert(tmdb.details(detailBody(), "movie", 597))
		assert.equal("https://image.tmdb.org/t/p/w500/poster.jpg", facts.poster_url)
		assert.equal("https://image.tmdb.org/t/p/w1280/wide.jpg", facts.backdrop_url)
		assert.equal("A voyage.", facts.overview)
		assert.same({ "Actor" }, facts.people)
		assert.equal("Passenger", facts.cast[1].role)
		assert.equal("https://www.themoviedb.org/movie/597", facts.source_url)
		assert.equal(1997, facts.year)
	end)
	it("handles absent/null metadata without fake data and refuses image path injection", function()
		local facts = assert(tmdb.details(detailBody({ poster_path = cjson.null, credits = cjson.null, release_dates = { results = cjson.null } }), "movie", 597))
		assert.is_nil(facts.poster_url)
		assert.same({}, facts.people)
		assert.is_nil(tmdb.image("/../../other.jpg"))
		assert.is_nil(tmdb.image("https://other.example/a.jpg"))
		assert.is_nil(tmdb.details(detailBody(), "movie", 999))
	end)
	it("encodes queries and uses only the TMDB HTTPS API", function()
		local url = assert(tmdb.searchUrl({ kind = "show", title = "A&B", year = 2001 }))
		assert.is_truthy(url:find("https://api.themoviedb.org/3/search/tv", 1, true))
		assert.is_truthy(url:find("query=A%26B", 1, true))
		assert.is_truthy(url:find("first_air_date_year=2001", 1, true))
	end)
end)

describe("persistent metadata catalog", function()
	local catalog, db, path, work
	before_each(function()
		catalog, db = nil, nil
		path = platform.path:join(platform.temp_dir(), "lunar_metadata_" .. os.time() .. "_" .. math.random(1e9) .. ".sqlite3")
		db = assert(sqlite.open(path)); assert(schema.migrate(db))
		catalog = Catalog.new(db, function() return 1000 end)
		local library = catalog:addLibrary("Films", "movie", "D:/Films")
		catalog:noteFile(library.id, "Titanic (1997).mkv", 100, 1, 1, { kind = "movie", title = "Titanic", year = 1997 })
		work = catalog:topWorkOfFile(library.id, "Titanic (1997).mkv")
	end)
	after_each(function() if catalog then catalog:close() end; if db then assert(db:close()) end; if path then os.remove(path) end end)
	it("keeps .nfo facts and local posters over provider data, including on later scans", function()
		catalog:saveFacts(work, { title = "My title", overview = "My plot", genres = { "My genre" }, people = { "My cast" } }, true)
		catalog:saveArt(work, "poster", "library", "poster.jpg")
		assert(catalog:saveMetadata(work, assert(tmdb.details(detailBody(), "movie", 597)), 1000, 2000))
		local item = catalog:item(work, "desktop")
		assert.equal("My title", item.title); assert.equal("My plot", item.overview)
		assert.same({ "My genre" }, item.genres); assert.same({ "My cast" }, item.people)
		assert.is_nil(item.poster_url)
		assert.equal("https://image.tmdb.org/t/p/w1280/wide.jpg", item.backdrop_url)
		assert.equal("tmdb", item.metadata.provider)
		catalog:saveFacts(work, { overview = "Encoder comment", genres = { "Encoder genre" }, people = { "Encoder name" } }, false)
		assert.equal("My plot", catalog:item(work, "desktop").overview)
		assert.same({ "My genre" }, catalog:item(work, "desktop").genres)
		assert.same({ "My cast" }, catalog:item(work, "desktop").people)
	end)
	it("uses provider data for missing fields and lets a later .nfo take precedence", function()
		assert(catalog:saveMetadata(work, assert(tmdb.details(detailBody(), "movie", 597)), 1000, 2000))
		local item = catalog:item(work, "desktop")
		assert.equal("A voyage.", item.overview); assert.same({ "Actor" }, item.people)
		catalog:saveFacts(work, { genres = { "Encoder genre" }, people = { "Encoder name" } }, false)
		assert.same({ "Drama" }, catalog:item(work, "desktop").genres)
		assert.same({ "Actor" }, catalog:item(work, "desktop").people)
		assert.equal("https://image.tmdb.org/t/p/w500/poster.jpg", item.poster_url)
		catalog:saveFacts(work, { overview = "Local", people = { "Local actor" } }, true)
		catalog:saveArt(work, "poster", "library", "local-poster.jpg")
		assert.equal("Local", catalog:item(work, "desktop").overview)
		assert.is_nil(catalog:item(work, "desktop").poster_url)
	end)
	it("recovers interrupted jobs, delays no-matches and stops after three failures", function()
		catalog:queueMissingMetadata(1000, 10)
		local job = assert(catalog:claimMetadata(1000))
		assert.is_nil(catalog:claimMetadata(1000))
		catalog:recoverMetadata(); job = assert(catalog:claimMetadata(1000))
		catalog:unmatchedMetadata(job, "ambiguous", 1000, 2000)
		assert.is_nil(catalog:claimMetadata(1999)); job = assert(catalog:claimMetadata(2000))
		for attempt = 1, 3 do
			catalog:failMetadata(job, "network", 2000, 2000)
			if attempt < 3 then job = assert(catalog:claimMetadata(2000)) end
		end
		assert.is_nil(catalog:claimMetadata(9999))
		assert.equal(1, catalog:metadataStatus().failed)
		assert(catalog:queueMetadata(work, 9999)); assert(catalog:claimMetadata(9999))
	end)
	it("does not extract fallback video frames when a provider already supplies a backdrop", function()
		local file_id = catalog:item(work, "desktop").files[1].id
		catalog:queueFrame(file_id)
		assert(catalog:saveMetadata(work, assert(tmdb.details(detailBody(), "movie", 597)), 1000, 2000))
		assert.is_nil(catalog:claimFrame())
		catalog:queueFrame(file_id)
		assert.is_nil(catalog:claimFrame())
	end)
	it('preserves a manual match when an older automatic lookup completes later',function()
		local now,pending=1000,{}
		local service=Metadata.new({catalog=catalog,now=function() return now end,getenv=function() return nil end,http=function(_,done) pending[#pending+1]=done end})
		service:tick();assert.equal(1,#pending)
		assert(service:apply(work,{provider='cinemeta',external_id='tt0120338',title='My chosen match',overview='Chosen description'}))
		pending[1]({ok=true,body='{"metas":[{"id":"tt0120338","name":"Titanic","releaseInfo":"1997"}]}'})
		now=1001;service:tick();assert.equal(2,#pending)
		pending[2]({ok=true,body='{"meta":{"id":"tt0120338","name":"Titanic","description":"Old automatic description"}}'})
		assert.equal('My chosen match',catalog:item(work,'desktop').title)
		assert.equal('Chosen description',catalog:item(work,'desktop').overview)
		assert.equal('cinemeta',assert(catalog:queueMetadata(work,1002)) and catalog:claimMetadata(1002).provider)
	end)
	it("fetches a search then details, keeps one job active and honors credentials", function()
		local pending, requests, now = {}, {}, 1000
		local service = Metadata.new({ catalog = catalog, provider='tmdb', now = function() return now end,
			getenv = function() return nil end, get_secret = function() return "private-token" end,
			http = function(request, done) requests[#requests + 1] = request; pending[#pending + 1] = done end })
		service:tick(); service:tick()
		assert.equal(1, #requests); assert.equal("working", service:status().state)
		assert.equal("Bearer private-token", requests[1].headers.Authorization)
		assert.is_nil(requests[1].url:find("private-token", 1, true))
		pending[1]({ ok = true, status = 200, body = cjson.encode({ results = { { id = 597, title = "Titanic", release_date = "1997-11-18" } } }) })
		assert.equal(1, #requests)
		now=now+1;service:tick();assert.equal(2,#requests)
		pending[2]({ ok = true, status = 200, body = detailBody() })
		assert.equal(1, service:status().matched); assert.equal("ready", service:status().state)
		service:tick(); assert.equal(2, #requests)
	end)
	it("stops retrying an invalid token until it changes", function()
		local token, calls = "bad", 0
		local service = Metadata.new({ catalog = catalog, provider='tmdb', now = function() return 1000 end,
			getenv = function() return nil end, get_secret = function() return token end,
			http = function(_, done) calls = calls + 1; done({ ok = false, status = 401 }) end })
		service:tick(); service:tick()
		assert.equal(1, calls); assert.equal('ready', service:status().state)
		assert.is_nil(service:status().error:find("bad", 1, true))
	end)
	it('uses keyless movie metadata without credentials', function()
		local seen
		local service = Metadata.new({ catalog = catalog, getenv = function() return nil end,
			http = function(request,done) seen=request;done({ok=true,status=200,body='{"metas":[]}'}) end })
		service:tick();assert.equal('ready',service:status().state)
		assert.is_truthy(seen.url:find('https://v3-cinemeta.strem.io/',1,true));assert.is_nil(seen.headers.Authorization)
		assert.is_nil(service:configure("token"))
	end)
end)
