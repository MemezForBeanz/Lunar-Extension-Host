local path = require("core.platform.path")

describe("core.platform.path (Windows rules)", function()
	local P = path.new({ windows = true })

	it("joins with backslashes and normalizes mixed separators", function()
		assert.are.equal("C:\\a\\b\\c.txt", P:join("C:\\a", "b/", "c.txt"))
		assert.are.equal("C:\\a\\b", P:normalize("C:/a//b/"))
		assert.are.equal("C:\\a\\c", P:normalize("C:\\a\\b\\..\\.\\c"))
	end)

	it("keeps UNC and long-path roots intact", function()
		assert.are.equal("\\\\server\\share\\dir\\f", P:join("\\\\server\\share", "dir", "f"))
		assert.are.equal("\\\\server\\share\\", P:normalize("\\\\server\\share\\x\\.."))
		assert.are.equal("\\\\?\\C:\\very\\long", P:normalize("\\\\?\\C:\\very\\long"))
	end)

	it("restarts at an absolute segment and never climbs above a root", function()
		assert.are.equal("D:\\x", P:join("C:\\a", "D:\\x"))
		assert.are.equal("C:\\", P:normalize("C:\\..\\.."))
		assert.are.equal("..\\x", P:normalize("..\\x"))
	end)

	it("keeps drive-relative paths relative to their drive", function()
		assert.are.equal("C:..\\x", P:normalize("C:..\\x"))
		assert.are.equal("C:x", P:join("C:", "x"))
		assert.are.equal("D:foo", P:join("C:\\base", "D:foo"))
		assert.are.equal("C:\\base\\foo", P:join("C:\\base", "c:foo"))
		assert.are.equal("C:\\x", P:join("C:\\base\\deep", "\\x"))
	end)

	it("passes extended-length paths through unchanged", function()
		assert.are.equal("\\\\?\\C:\\a\\..\\..\\x", P:normalize("\\\\?\\C:\\a\\..\\..\\x"))
		assert.are.equal("\\\\?\\UNC\\server\\share\\..\\x", P:normalize("\\\\?\\UNC\\server\\share\\..\\x"))
		assert.are.equal("\\\\?\\C:\\long\\name", P:join("\\\\?\\C:\\long", "name"))
		assert.is_true(P:is_absolute("\\\\?\\UNC\\server\\share"))
	end)

	it("adds the separator a share root needs", function()
		assert.are.equal("\\\\server\\share\\x", P:normalize("\\\\server\\share/x"))
	end)

	it("knows what is absolute", function()
		assert.is_true(P:is_absolute("C:\\x"))
		assert.is_true(P:is_absolute("\\\\srv\\share"))
		assert.is_false(P:is_absolute("C:x"))
		assert.is_false(P:is_absolute("\\x"))
		assert.is_false(P:is_absolute("x\\y"))
	end)

	it("splits names and compares case-insensitively", function()
		assert.are.equal("C:\\a", P:dirname("C:\\a\\b.lua"))
		assert.are.equal("C:\\", P:dirname("C:\\b.lua"))
		assert.are.equal("b.lua", P:basename("C:\\a\\b.lua"))
		local base, ext = P:split_ext("C:\\a\\b.tar.gz")
		assert.are.equal("C:\\a\\b.tar", base)
		assert.are.equal(".gz", ext)
		assert.is_true(P:same("C:/Repo/Src", "c:\\repo\\src\\"))
	end)
end)

describe("core.platform.path (POSIX rules)", function()
	local P = path.new({ windows = false })

	it("uses forward slashes and treats backslash as a name character", function()
		assert.are.equal("/home/u/a\\b", P:join("/home/u", "a\\b"))
		assert.are.equal("/a/c", P:normalize("/a//b/../c/."))
	end)

	it("is case-sensitive and knows its root", function()
		assert.is_false(P:same("/Repo", "/repo"))
		assert.is_true(P:is_absolute("/x"))
		assert.is_false(P:is_absolute("C:\\x"))
		assert.are.equal("/", P:dirname("/x"))
		assert.are.equal(".", P:dirname("x"))
	end)
end)
