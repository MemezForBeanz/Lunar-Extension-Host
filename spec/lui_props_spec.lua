-- core.lui typed props: what each primitive's props become as iup attributes, the escape
-- hatches, `hidden`, and palette tokens that re-resolve on a theme switch.
local T = require("core.lui.test")
local ui = require("core.lui")
local P = require("core.lui.props")

local iup, Element
before_each(function() iup, _, _, Element = T.boot({}) end)

local function make(el)
	local root = ui.mount(el, { iup = iup })
	return root:widget(), root
end

-- The element's own attributes (not inherited or defaulted).
local function own(h, name) return Element.own(h, name) end

describe("lui props: common", function()
	it("maps the shared props of every primitive", function()
		local h = make(ui.Text{ "x", visible = false, enabled = false, tip = "help", font = "Segoe UI, 10",
			role = "settingslabel", name = "lbl", expand = "horizontal", minSize = { 10, 20 },
			maxSize = { 300 }, canFocus = true, cursor = "HAND" })
		assert.equal("NO", own(h, "VISIBLE"))
		assert.equal("NO", own(h, "ACTIVE"))
		assert.equal("help", own(h, "TIP"))
		assert.equal("Segoe UI, 10", own(h, "FONT"))
		assert.equal("settingslabel", own(h, "THEMEROLE"))
		assert.equal("lbl", own(h, "NAME"))
		assert.equal("HORIZONTAL", own(h, "EXPAND"))
		assert.equal("10x20", own(h, "MINSIZE"))
		assert.equal("300x", own(h, "MAXSIZE"))
		assert.equal("YES", own(h, "CANFOCUS"))
		assert.equal("HAND", own(h, "CURSOR"))
	end)

	it("maps expand words and booleans", function()
		assert.equal("YES", P.expand(true))
		assert.equal("NO", P.expand(false))
		assert.equal("VERTICAL", P.expand("vertical"))
		assert.equal("HORIZONTALFREE", P.expand("horizontalfree"))
	end)

	it("builds RASTERSIZE from size, width and height", function()
		assert.equal("48x28", own(make(ui.Button{ size = { 48, 28 } }), "RASTERSIZE"))
		assert.equal("220x", own(make(ui.Button{ width = 220 }), "RASTERSIZE"))
		assert.equal("x28", own(make(ui.VBox{ height = 28 }), "RASTERSIZE"))
		assert.equal("40x10", own(make(ui.Label{ width = 40, height = 10 }), "RASTERSIZE"))
		assert.equal("320x24", own(make(ui.Frame{ size = "320x24" }), "RASTERSIZE"))
	end)

	it("hides out of the layout with hidden, and shows again", function()
		local h, root = make(ui.HBox{ hidden = true })
		assert.equal("YES", own(h, "FLOATING"))
		assert.equal("NO", own(h, "VISIBLE"))
		root:update(ui.HBox{ hidden = false })
		assert.equal("NO", own(h, "FLOATING"))
		assert.equal("YES", own(h, "VISIBLE"))
	end)

	it("accepts colours as r g b, tables, hex and palette tokens", function()
		P.setPalette(function() return { surface = "10 20 30" } end)
		assert.equal("1 2 3", P.color("1 2 3"))
		assert.equal("1 2 3", P.color({ 1, 2, 3 }))
		assert.equal("255 128 0", P.color("#ff8000"))
		assert.equal("255 255 0", P.color("#ff0"))
		assert.equal("10 20 30", P.color("surface"))
		assert.is_nil(P.color("missing_token"))
		assert.equal("9 9 9", P.color(ui.token("missing_token", "9 9 9")))
		local h = make(ui.HBox{ bg = "surface", fg = "#000000" })
		assert.equal("10 20 30", own(h, "BGCOLOR"))
		assert.equal("0 0 0", own(h, "FGCOLOR"))
		P.setPalette(nil)
	end)

	it("passes UPPERCASE props through as raw attributes", function()
		local h = make(ui.Button{ "x", TEXTELLIPSIS = true, SPACING = 8, IMAGEPOSITION = "LEFT", TIP = "raw" })
		assert.equal("YES", own(h, "TEXTELLIPSIS"))
		assert.equal("8", own(h, "SPACING"))
		assert.equal("LEFT", own(h, "IMAGEPOSITION"))
		assert.equal("raw", own(h, "TIP"))
	end)
end)

describe("lui props: primitives", function()
	it("VBox and HBox: gap, padding, align per direction, homogeneous", function()
		local v = make(ui.VBox{ gap = 8, padding = 16, align = "center", homogeneous = true })
		assert.equal("8", own(v, "GAP"))
		assert.equal("16x16", own(v, "MARGIN"))
		assert.equal("ACENTER", own(v, "ALIGNMENT"))
		assert.equal("YES", own(v, "HOMOGENEOUS"))
		assert.equal("ARIGHT", own(make(ui.VBox{ align = "end" }), "ALIGNMENT"))
		local hb = make(ui.HBox{ padding = { 8, 0 }, align = "start" })
		assert.equal("8x0", own(hb, "MARGIN"))
		assert.equal("ATOP", own(hb, "ALIGNMENT"))
		assert.equal("ABOTTOM", own(make(ui.HBox{ align = "end" }), "ALIGNMENT"))
	end)

	it("ZBox and Tabs: 1-based value onto VALUEPOS", function()
		local z = make(ui.ZBox{ value = 2, ui.Text{ "a" }, ui.Text{ "b" } })
		assert.equal("zbox", iup.GetClassName(z))
		assert.equal("1", iup.GetAttribute(z, "VALUEPOS"))
		local t = make(ui.Tabs{ value = 1, ui.VBox{ tabTitle = "One" }, ui.VBox{ tabTitle = "Two" } })
		assert.equal("flattabs", iup.GetClassName(t))
		assert.equal("One", own(iup.GetChild(t, 0), "TABTITLE"))
		assert.equal("Two", own(iup.GetChild(t, 1), "TABTITLE"))
	end)

	it("Spacer, Frame, Scroll, Separator, Split: classes and props", function()
		assert.equal("fill", iup.GetClassName(make(ui.Spacer{})))
		local f = make(ui.Frame{ title = "", padding = 4, ui.Text{ "in" } })
		assert.equal("flatframe", iup.GetClassName(f))
		assert.equal("", own(f, "TITLE"))
		assert.equal("4x4", own(f, "MARGIN"))
		assert.equal("flatscrollbox", iup.GetClassName(make(ui.Scroll{ ui.VBox{} })))
		local s = make(ui.Separator{ orientation = "horizontal" })
		assert.equal("flatseparator", iup.GetClassName(s))
		assert.equal("HORIZONTAL", own(s, "ORIENTATION"))
		local sp = make(ui.Split{ orientation = "vertical", value = 300, barSize = 5, ui.VBox{}, ui.VBox{} })
		assert.equal("split", iup.GetClassName(sp))
		assert.equal("VERTICAL", iup.GetAttribute(sp, "ORIENTATION"))
		assert.equal("300", iup.GetAttribute(sp, "VALUE"))
		assert.equal("5", iup.GetAttribute(sp, "BARSIZE"))
	end)

	it("Text, Label, Image and Button: content, alignment, ellipsis, padding, variant", function()
		local t = make(ui.Text{ "Hello ", "world", wrap = true, ellipsis = true, align = "left:center" })
		assert.equal("flatlabel", iup.GetClassName(t))
		assert.equal("Hello world", own(t, "TITLE"))
		assert.equal("YES", own(t, "TEXTWRAP"))
		assert.equal("YES", own(t, "TEXTELLIPSIS"))
		assert.equal("ALEFT:ACENTER", own(t, "ALIGNMENT"))
		local l = make(ui.Label{ "native", ellipsis = true, wrap = true, padding = { 6, 0 } })
		assert.equal("label", iup.GetClassName(l))
		assert.equal("YES", own(l, "ELLIPSIS"))
		assert.equal("YES", own(l, "WORDWRAP"))
		assert.equal("6x0", own(l, "PADDING"))
		iup.SetHandle("lui_spec_img", iup.imagergba({ width = 1, height = 1, pixels = { 0, 0, 0, 0 } }))
		local img = make(ui.Image{ image = "lui_spec_img" })
		assert.equal("label", iup.GetClassName(img))
		assert.equal("lui_spec_img", own(img, "IMAGE"))
		local b = make(ui.Button{ "Save", variant = "primary", padding = { 12, 5 }, ellipsis = true })
		assert.equal("flatbutton", iup.GetClassName(b))
		assert.equal("Save", own(b, "TITLE"))
		assert.equal("primary_btn", own(b, "THEMEROLE"))
		assert.equal("12x5", own(b, "PADDING"))
		assert.equal("YES", own(b, "TEXTELLIPSIS"))
		assert.is_nil(own(make(ui.Button{}), "TITLE"), "no text children: no TITLE at all")
		assert.equal("", own(make(ui.Button{ "" }), "TITLE"))
	end)

	it("Toggle, Input and List: values", function()
		local tg = make(ui.Toggle{ "Wrap", checked = true, switch = true })
		assert.equal("flattoggle", iup.GetClassName(tg))
		assert.equal("ON", iup.GetAttribute(tg, "VALUE"))
		assert.equal("YES", own(tg, "SWITCH"))
		local inp = make(ui.Input{ value = "abc", placeholder = "Name", readonly = true, password = true, border = false, columns = 28 })
		assert.equal("text", iup.GetClassName(inp))
		assert.equal("abc", iup.GetAttribute(inp, "VALUE"))
		assert.equal("Name", own(inp, "CUEBANNER"))
		assert.equal("YES", own(inp, "READONLY"))
		assert.equal("YES", own(inp, "PASSWORD"))
		assert.equal("NO", own(inp, "BORDER"))
		assert.equal("28", own(inp, "VISIBLECOLUMNS"))
		local list, root = make(ui.List{ items = { "a", "b", "c" }, value = 2, lines = 4 })
		assert.equal("flatlist", iup.GetClassName(list))
		assert.equal("3", iup.GetAttribute(list, "COUNT"))
		assert.equal("2", iup.GetAttribute(list, "VALUE"))
		assert.equal("4", own(list, "VISIBLELINES"))
		root:update(ui.List{ items = { "x" }, value = 1, lines = 4 })
		assert.equal("1", iup.GetAttribute(list, "COUNT"))
		assert.equal("x", own(list, "1"))
	end)

	it("Canvas, Dialog and Dropdown", function()
		assert.equal("canvas", iup.GetClassName(make(ui.Canvas{ size = { 10, 10 } })))
		local d = make(ui.Dialog{ title = "Name", RASTERSIZE = "380x150", ui.VBox{} })
		assert.equal("dialog", iup.GetClassName(d))
		assert.equal("Name", own(d, "TITLE"))
		assert.equal("380x150", own(d, "RASTERSIZE"))
		local dd, root = make(ui.Dropdown{ items = { "Small", "Large" }, value = 2, tip = "Size" })
		assert.equal("dropbutton", iup.GetClassName(dd))
		assert.equal("Large", iup.GetAttribute(dd, "TITLE"))
		assert.equal("Size", own(dd, "TIP"))
		root:update(ui.Dropdown{ items = { "Small", "Large" }, value = 1, tip = "Size" })
		assert.equal("Small", iup.GetAttribute(dd, "TITLE"))
	end)

	it("ui.host wraps any iup class with raw attributes", function()
		local Seek = ui.host("flatseparator", { leaf = true })
		local h = make(Seek{ ORIENTATION = "HORIZONTAL", tip = "t" })
		assert.equal("flatseparator", iup.GetClassName(h))
		assert.equal("HORIZONTAL", own(h, "ORIENTATION"))
		assert.equal("t", own(h, "TIP"))
		assert.equal(Seek, ui.host("flatseparator", { leaf = true }), "cached per class")
	end)
end)

describe("lui palette tokens", function()
	it("re-resolve on a theme switch through ThemeReactor", function()
		local TR = require("core.ui.ThemeReactor")
		local applied
		local tm = { onApply = function(_, fn) applied = fn end }
		TR.bindThemeManager(tm)
		local palette = { accent = "1 1 1" }
		local theme = { palette = function() return palette end }
		applied(theme)
		local h, root = make(ui.HBox{ bg = "accent", fg = "2 2 2" })
		assert.equal("1 1 1", own(h, "BGCOLOR"))
		palette = { accent = "9 9 9" }
		applied(theme)
		assert.equal("9 9 9", own(h, "BGCOLOR"))
		assert.equal("2 2 2", own(h, "FGCOLOR"))
		-- a theme pass that wrote over the token colour is put right afterwards
		iup.SetAttribute(h, "BGCOLOR", "0 0 0")
		TR.themePassDone()
		assert.equal("9 9 9", own(h, "BGCOLOR"))
		root:unmount()
		applied({ palette = function() return {} end })
	end)
end)
