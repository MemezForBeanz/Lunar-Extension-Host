local Shell = require("core.lib.LunarShell")
local Buffer = require("core.lib.TerminalBuffer")

describe("Lunar prompt parsing", function()
	it("groups quotes, preserves empty args and Windows paths", function()
		assert.same({ "show", "C:\\work folder\\a.py", "", "a b" }, Shell.parse([[show "C:\work folder\a.py" "" 'a b']]))
	end)
	it("preserves metacharacters as literal arguments", function()
		assert.same({ "test.lua", ";", "&&", "$HOME", "$(whoami)", "a|b" }, Shell.parse("test.lua ; && $HOME $(whoami) a|b"))
	end)
	it("accepts quoted Windows directories ending in a backslash", function()
		assert.same({ "show", "C:\\work folder\\" }, Shell.parse([[show "C:\work folder\"]]))
	end)
	it("rejects incomplete quotes for execution, accepts them for completion", function()
		local args, why = Shell.parse('show "unfinished')
		assert.is_nil(args); assert.matches("Unclosed", why)
		assert.same({ "show", "unfinished" }, Shell.parse('show "unfinished', true))
	end)
	it("records byte ranges for live colours", function()
		local styles = Shell.new():styles([[show "a b.py" --flag src/a.lua]])
		assert.equal("keyword", styles[1].role)
		assert.equal(5, styles[2].start); assert.equal("string", styles[2].role)
		assert.equal("preprocessor", styles[3].role); assert.equal("type", styles[4].role)
		assert.equal("error", Shell.new():styles("typo")[1].role)
	end)
end)

describe("Lunar prompt commands", function()
	it("routes every built-in without spawning", function()
		local s = Shell.new()
		for _, name in ipairs(s:names()) do
			if name ~= "headless" then
				local result = assert(s:execute(name .. ((name == "open" or name == "show") and " a.lua" or "")))
				assert.is_not.equal("cli", result.action)
			end
		end
	end)
	it("turns headless into the real CLI option and strips the optional CLI prefix", function()
		local s = Shell.new()
		assert.same({ "--headless", "--for", "1" }, s:execute("headless --for 1").argv)
		assert.same({ "a.lua", "two words" }, s:execute('lunar-cli a.lua "two words"').argv)
		assert.same({ "cmd", "/c", "test" }, s:execute("cmd /c test").argv)
	end)
	it("describes individual commands and rejects missing arguments", function()
		local s = Shell.new()
		assert.matches("show <file>", s:execute("help show").text, 1, true)
		assert.matches("Unknown command", s:execute("help missing").text)
		local result, why = s:execute("show")
		assert.is_nil(result); assert.matches("Usage", why)
	end)
	it("lets another module register a command without UI dependencies", function()
		local s = Shell.new()
		s:register("example", { usage = "example", description = "An extension command.", run = function(_, args) return args[2] end })
		assert.equal("value", s:execute("example value").text)
		assert.is_nil(Shell.new().commands.example)
	end)
	it("extracts file references without losing a drive letter or spaces", function()
		local path, line, column = Shell.reference("C:\\work folder\\a.py:23:9: error: nope")
		assert.equal("C:\\work folder\\a.py", path); assert.equal(23, line); assert.equal(9, column)
		assert.is_nil(Shell.reference("plain output"))
	end)
end)

describe("Lunar prompt history and completion", function()
	it("bounds history, removes consecutive duplicates, and restores a draft", function()
		local s = Shell.new({ history_limit = 2 })
		s:remember("one"); s:remember("two"); s:remember("two"); s:remember("three")
		assert.same({ "two", "three" }, s.history)
		assert.equal("three", s:previous("draft")); assert.equal("two", s:previous())
		assert.equal("two", s:previous()); assert.equal("three", s:next()); assert.equal("draft", s:next())
	end)
	it("handles empty history", function()
		local s = Shell.new(); assert.equal("draft", s:previous("draft")); assert.equal("draft", s:next())
	end)
	it("completes commands and retains text after the caret", function()
		local s = Shell.new()
		assert.equal("version ", (s:complete("ver")))
		assert.equal("version  tail", (s:complete("ver tail", 3)))
		assert.equal("help version ", (s:complete("help ver")))
	end)
	it("completes flags and quoted paths", function()
		local s = Shell.new()
		assert.equal("headless --until-idle ", (s:complete("headless --unt")))
		assert.equal('show "two words.lua" ', (s:complete('show "two', nil, function() return { "two words.lua" } end)))
	end)
	it("completes a script as the first argument and spaces inside a quote", function()
		local s = Shell.new()
		assert.equal("sample.lua ", (s:complete("samp", nil, function() return { "sample.lua" } end)))
		assert.equal('show "two words.lua" ', (s:complete('show "two ', nil, function() return { "two words.lua" } end)))
	end)
	it("returns the common prefix and candidates when ambiguous", function()
		local text, matches = Shell.new():complete("show a", nil, function() return { "alpha.lua", "alpine.lua" } end)
		assert.equal("show alp", text); assert.equal(2, #matches)
	end)
end)

describe("terminal scrollback", function()
	it("evicts old text and its colours together", function()
		local buffer = Buffer.new(12)
		buffer:append("old text", { language = "lua" }); buffer:append("new text", { role = "error" })
		local text, fragments = buffer:snapshot()
		assert.equal("new text", text); assert.equal(0, fragments[1].start); assert.equal("error", fragments[1].role)
	end)
	it("caps a single large write and discards offsets into the removed part", function()
		local buffer = Buffer.new(4)
		buffer:append("abcdef", { tokens = { { start = 5 } } })
		local text, fragments = buffer:snapshot()
		assert.equal("cdef", text); assert.is_nil(fragments[1].tokens)
	end)
	it("normalizes line endings and removes ANSI escapes", function()
		local buffer = Buffer.new(); buffer:append("\27[31merror\27[0m\r\nnext\r")
		assert.equal("error\nnext\n", (buffer:snapshot()))
		buffer:clear(); assert.equal("", (buffer:snapshot()))
	end)
	it("preserves printed file bytes so semantic token offsets stay valid", function()
		local buffer = Buffer.new(); buffer:append("x\r\ny\r\n", { language = "python" })
		assert.equal("x\r\ny\r\n", (buffer:snapshot()))
	end)
end)
