local StateIcon = require("core.ui.StateIcon")
local Director = require("core.classes.MotionDirector")
describe("StateIcon", function()
 local now, d, painted, icon
 before_each(function()
  now=0; painted={}
  d=Director({clock=function() return now end, enabled=true, respect_system=false, widgets=false})
  icon=StateIcon.new({}, {kind="run", visible=function() return true end,
   frame=function(key,svg) return svg end, paint=function(svg) painted[#painted+1]=svg end})
 end)
 after_each(function() icon:destroy(); d:shutdown(); StateIcon.bindDirector(nil) end)
 it("publishes all eleven kinds and their initial states",function()
  assert.equals(11,#StateIcon.kinds())
  for _,kind in ipairs(StateIcon.kinds()) do
   local def=StateIcon.definition(kind)
   for name in pairs(def.states) do
    assert.matches("<svg",StateIcon.svg(kind,def.initial,name,1))
   end
  end
 end)
 it("rejects unknown states",function() assert.has_error(function() icon:set("wat") end) end)
 it("keeps the outgoing row colour until the incoming glyph appears",function()
  local roles={}
  local row=StateIcon.new({}, {kind="row",visible=function() return true end,
   frame=function(_,svg) return svg end,paint=function(_,role) roles[#roles+1]=role end})
  row.current,row.from,row.t="ok","failed",.25; row:_draw()
  assert.equals("error",roles[#roles])
  row.t=.75; row:_draw(); assert.equals("success",roles[#roles])
  row.current,row.from,row.t="skipped","skipped",1; row:_draw()
  assert.equals("neutral",roles[#roles]); row:destroy()
 end)
 it("shares finished row glyphs with legacy status handles",function()
  local V=require("core.ui.VectorIcon")
  local available,render,color=V.available,V.imageHandle,V.roleColor
  V.available=true; V.imageHandle=function(_,opts) return opts end; V.roleColor=function(role) return role end
  local ok,err=pcall(function()
   local status=assert(loadfile("src/lua/core/ui/StatusIcon.lua"))()
   local failed=status.imageHandle({},"unused","build_error",16)
   local f=assert(io.open(failed.path,"rb")); local svg=f:read("*a"); f:close()
   assert.equals(StateIcon.svg("row","failed","failed",1),svg)
   local skipped=status.imageHandle({},"unused","build_skip",16)
   assert.equals(V.roleColor("neutral"),skipped.color)
  end)
  V.available,V.imageHandle,V.roleColor=available,render,color
  assert.is_true(ok,tostring(err))
 end)
 it("shows only one glyph on either side of the transition midpoint",function()
  for _,t in ipairs({.25,.5,.75}) do
   local svg=StateIcon.svg("copy","ready","copied",t)
   local _,paths=svg:gsub("<path ","")
   assert.equals(1,paths)
  end
 end)
 it("closes the connection halves without crossfading plugs",function()
  assert.matches('translate%(%-4 0%)',StateIcon.svg("connection","offline","connected",0))
  assert.matches('translate%(%-2 0%)',StateIcon.svg("connection","offline","connected",.5))
  assert.matches('translate%(0 0%)',StateIcon.svg("connection","offline","connected",1))
  assert.equals("info",StateIcon.definition("refresh").states.available.role)
 end)
 it("fades badges along with their glyph at the midpoint",function()
  local svg=StateIcon.svg("refresh","checking","available",.5)
  assert.matches('<circle opacity="0"',svg)
  assert.matches('<path opacity="0"',svg)
 end)
 it("animates real work, then stops on failure",function()
  icon:set("working"); now=.2; d:tick(now)
  assert.equals("working",icon:state())
  assert.equals(1,d:activeCount())
  icon:set("failed"); now=.5; d:tick(now)
  assert.equals(0,d:activeCount())
 end)
 it("holds success for 1200ms and returns to ready",function()
  icon:set("succeeded"); now=.16; d:tick(now)
  assert.equals("succeeded",icon:state())
  now=1.37; d:tick(now); now=1.6; d:tick(now)
  assert.equals("ready",icon:state())
  assert.equals(0,d:activeCount())
 end)
 it("does not schedule a loop with reduced motion",function()
  d:configure({enabled=false}); icon:set("working")
  assert.equals("working",icon:state()); assert.equals(0,d:activeCount())
 end)
 it("does not animate hidden work",function()
  icon.visible=function() return false end; icon:set("working")
  assert.equals(0,d:activeCount())
 end)
 it("determinate progress has no idle clock",function()
  icon:set("working",{progress=.5}); now=.2; d:tick(now)
  assert.equals(0,d:activeCount())
 end)
 it("cancels on destroy",function()
  icon:set("working"); icon:destroy(); assert.equals(0,d:activeCount())
 end)
 it("registers extension path data",function()
  StateIcon.register("probe",{initial="off",states={off={path="M4 4H28"}}})
  assert.matches("M4 4H28",StateIcon.svg("probe","off","off",1))
 end)
end)
