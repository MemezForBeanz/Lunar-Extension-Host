local package_ext = require('installer.package')
local plan = require('installer.plan')
local payload = require('spec.support.installer_payload')
local lfs = require('lfs')
describe('installer extension packaging', function()
 local root, builtin, extras, dest
 before_each(function()
  root = payload.new(); builtin = root .. '/builtins'; extras = root .. '/extensions'; dest = root .. '/stage'
  payload.write(builtin .. '/base/init.lua', 'return {}')
  payload.write(builtin .. '/base/manifest.json', payload.manifest('base', 'Built-in'))
 end)
 after_each(function() payload.rmtree(root) end)
 it('offers all project folder and single-file extensions with their metadata and companions', function()
  payload.write(extras .. '/server/init.lua', 'return {}')
  payload.write(extras .. '/server/manifest.json', payload.manifest('server', 'Media Server', {'"schema_version":2', '"host_api":4', '"modes":["headless"]'}))
  payload.write(extras .. '/server/libs/worker.lua', 'return "worker"')
  payload.write(extras .. '/player.lua', 'return {}')
  payload.write(extras .. '/player.manifest.json', payload.manifest('player', 'Media Player'))
  payload.write(extras .. '/server.zip', 'not an extension')
  payload.write(extras .. '/notes/README.md', 'author notes')
  package_ext.stage(builtin, extras, dest, {os = 'windows'})
  local offered, skipped, support = plan.scan_extensions(dest, {os = 'windows'})
  assert.equal(3, #offered); assert.equal(0, #skipped); assert.equal(0, #support)
  assert.equal('worker', payload.read(dest .. '/server/libs/worker.lua'):match('"(.-)"'))
  assert.is_truthy(payload.read(dest .. '/player.manifest.json'))
  assert.is_nil(lfs.attributes(dest .. '/server.zip'))
  assert.is_nil(lfs.attributes(dest .. '/notes'))
  assert.equal(0, #plan.select(offered, 'none'))
  local chosen = plan.select(offered, {'server'})
  assert.equal(1, #chosen); assert.equal('Media Server', chosen[1].name)
 end)
 it('refuses duplicate ids across the two roots before writing the payload', function()
  payload.write(extras .. '/other/init.lua', 'return {}')
  payload.write(extras .. '/other/manifest.json', payload.manifest('base', 'Duplicate'))
  assert.has_error(function() package_ext.stage(builtin, extras, dest) end, 'Duplicate extension id: base')
  assert.is_nil(lfs.attributes(dest))
 end)
 it('refuses destination name collisions even for different manifest ids', function()
  payload.write(extras .. '/base/init.lua', 'return {}')
  payload.write(extras .. '/base/manifest.json', payload.manifest('different', 'Other'))
  assert.has_error(function() package_ext.stage(builtin, extras, dest) end, 'Extension payload name collision: base')
 end)
 it('applies the same platform eligibility rules as the installer', function()
  payload.write(extras .. '/win/init.lua', 'return {}')
  payload.write(extras .. '/win/manifest.json', payload.manifest('win', 'Windows', {'"schema_version":2', '"platforms":["windows"]'}))
  local offered, skipped = package_ext.stage(builtin, extras, dest, {os = 'linux'})
  assert.equal(1, #offered); assert.equal(1, #skipped)
  assert.is_nil(lfs.attributes(dest .. '/win'))
 end)
end)
