local iup = require("core.imgui.iup")
local E = require("core.imgui.Element")
local C = require("core.imgui.Classes")
local sci = require("core.imgui.native.sci")
local S = require("core.imgui.widgets.scintilla")
local R = require("core.imgui.Runtime")
local Null = require("core.imgui.backend.Null")
describe("Scintilla rendered wrapping", function()
	local c, st, backend, cw, ch
	local function open(text, columns, mode)
		backend = Null.new(); R.init(backend)
		c = iup.scintilla{ VALUE = text }; st = E.state(c)
		cw, ch = S._style_font(c, st, 32):charsize()
		st.x, st.y, st.w, st.h = 0, 0, columns * cw + 8, 4 * ch
		sci.send(c, 2268, mode or 1)
	end
	after_each(function() if c then iup.Destroy(c) end end)
	it("wraps words, characters, whitespace and long words", function()
		open("ab cd ef", 4)
		assert.equal(3, sci.send(c, 2235, 0))
		assert.equal(3, S._layout(c, st):line(0)[1].finish)
		sci.send(c, 2268, 2); assert.equal(2, sci.send(c, 2235, 0))
		sci.send(c, 2268, 3); assert.equal(3, sci.send(c, 2235, 0))
		c.VALUE = "abcdefghij"; assert.equal(3, sci.send(c, 2235, 0))
		c.WORDWRAP = "NONE"; assert.equal(1, sci.send(c, 2235, 0))
		c.WORDWRAP = "CHAR"; assert.equal(2, sci.send(c, 2269))
	end)
	it("measures UTF-8 and tabs without breaking a character", function()
		open("ééé\tX", 3, 2)
		local rows = S._layout(c, st):line(0)
		assert.equal(6, rows[1].finish)
		assert.equal(7, rows[2].finish)
		assert.equal(3, #rows)
	end)
	it("maps document and display lines and round trips points", function()
		open("abcdef\nxy", 3, 2)
		assert.equal(2, sci.send(c, 2220, 1))
		assert.equal(0, sci.send(c, 2221, 1)); assert.equal(1, sci.send(c, 2221, 2))
		for _, p in ipairs({ 0, 1, 3, 4, 7, 8 }) do
			local x, y = sci.send(c, 2164, 0, p), sci.send(c, 2165, 0, p)
			assert.equal(p, sci.send(c, 2022, x, y))
		end
		assert.equal(4, sci.send(c, 2370))
		sci.send(c, 2613, 1); assert.equal(1, sci.send(c, 2152))
		assert.equal(0, sci.send(c, 2165, 0, 4))
	end)
	it("moves vertically by display rows and hits the wrapped mouse row", function()
		open("abcdefghijkl", 4, 2)
		sci.send(c, 2025, 2)
		local function key(k) C.get("scintilla").event(c, st, { type = "key", key = k, mods = {} }, R) end
		key(iup.K_DOWN); assert.equal(6, sci.send(c, 2008))
		key(iup.K_DOWN); assert.equal(10, sci.send(c, 2008))
		key(iup.K_UP); assert.equal(6, sci.send(c, 2008))
		key(iup.K_HOME); assert.equal(0, sci.send(c, 2008))
		key(iup.K_END); assert.equal(12, sci.send(c, 2008))
		C.get("scintilla").event(c, st, { type = "press", button = 1, lx = 4 + cw, ly = ch + 1, mods = {} }, R)
		assert.equal(5, sci.send(c, 2008))
	end)
	it("supports display and wrap Home/End commands and extending", function()
		open("abcdefghijkl", 4, 2); sci.send(c, 2025, 6)
		sci.send(c, 2349); assert.equal(4, sci.send(c, 2008))
		sci.send(c, 2349); assert.equal(0, sci.send(c, 2008))
		sci.send(c, 2025, 6); sci.send(c, 2451); assert.equal(8, sci.send(c, 2008))
		sci.send(c, 2025, 6); sci.send(c, 2346); assert.equal(4, sci.send(c, 2008)); assert.equal(6, sci.send(c, 2009))
	end)
	it("invalidates layout for text, width, tab width, fonts, zoom and indent", function()
		open("abcdefgh", 4, 2)
		local a = S._layout(c, st)
		assert.equal(a, S._layout(c, st))
		st.w = 2 * cw + 8; assert.equal(4, sci.send(c, 2235, 0))
		assert.is_not.equal(a, S._layout(c, st))
		c.VALUE = "ab"; assert.equal(1, sci.send(c, 2235, 0))
		c.VALUE = "abcdefgh"; sci.send(c, 2464, 1)
		assert.equal(7, sci.send(c, 2235, 0))
		a = S._layout(c, st); sci.send(c, 2036, 8); assert.is_not.equal(a, S._layout(c, st))
		a = S._layout(c, st); sci.send(c, 2373, 3); assert.is_not.equal(a, S._layout(c, st))
		a = S._layout(c, st); c.FONT = "Consolas, 20"; assert.is_not.equal(a, S._layout(c, st))
	end)
	it("draws sub-lines, selection, indicators, markers and one line number", function()
		open("abcdef", 3, 2)
		sci.send(c, 2242, 0, 20); st.w = st.w + 20
		sci.send(c, 2242, 1, 14); st.w = st.w + 14
		sci.send(c, 2160, 1, 5); sci.send(c, 2500, 1); sci.send(c, 2504, 1, 4)
		sci.send(c, 2043, 0, 1)
		local dc = require("core.imgui.Draw").new(backend); dc:begin(st.w, st.h)
		C.get("scintilla").draw(c, st, dc, { focused = function() return c end })
		local text, numbers, ys, markers, strokes, selections = {}, 0, {}, 0, 0, 0
		for _, call in ipairs(backend.frame_calls) do
			if call[1] == "circle" then markers = markers + 1 end
			if call[1] == "line" then strokes = strokes + 1 end
			if call[1] == "rect_filled" and call[6] == require("core.imgui.Color").parse("100 140 220") then selections = selections + 1 end
			if call[1] == "text" then
				if call[7] == "1" then numbers = numbers + 1 else text[#text + 1] = call[7]; ys[call[5]] = true end
			end
		end
		assert.equal("abcdef", table.concat(text)); assert.equal(1, numbers)
		local row_count = 0; for _ in pairs(ys) do row_count = row_count + 1 end
		assert.equal(2, row_count); assert.equal(1, markers); assert.equal(2, selections); assert.is_true(strokes > 1)
	end)
	it("wraps only demanded lines of a 50,000-line document", function()
		open(string.rep("abcdefghij\n", 49999) .. "abcdefghij", 5, 2)
		local dc = require("core.imgui.Draw").new(backend); dc:begin(st.w, st.h)
		C.get("scintilla").draw(c, st, dc)
		local wrap = S._layout(c, st)
		assert.is_true(wrap.through < 10)
		assert.equal(100000, wrap:visible(50000))
		assert.equal(99998, sci.send(c, 2220, 49999))
	end)
	it("uses continuation indentation, reserves start flags and suppresses horizontal scrolling", function()
		open("  abcdefghij", 5, 2)
		sci.send(c, 2472, 1)
		assert.equal(2 * cw, S._layout(c, st):line(0)[2].indent)
		sci.send(c, 2472, 0); sci.send(c, 2460, 2); sci.send(c, 2462, 1)
		assert.equal(cw, S._layout(c, st):line(0)[2].indent)
		assert.equal(2, sci.send(c, 2461)); assert.equal(1, sci.send(c, 2463))
		sci.send(c, 2274, 1000); sci.send(c, 2397, 20)
		assert.equal(0, sci.send(c, 2398)); assert.equal(0, sci.send(c, 2275))
	end)
	it("uses extra ascent/descent for display geometry and tracks painted unwrapped width", function()
		open("abcdefgh", 4, 2)
		sci.send(c, 2525, 2); sci.send(c, 2527, 3)
		assert.equal(ch + 5, sci.send(c, 2165, 0, 4))
		sci.send(c, 2268, 0); sci.send(c, 2516, 1); sci.send(c, 2274, 1)
		local dc = require("core.imgui.Draw").new(backend); dc:begin(st.w, st.h)
		C.get("scintilla").draw(c, st, dc)
		assert.is_true(sci.send(c, 2275) >= cw * 8)
	end)
	it("scrolls and pages through wrapped rows and uses Alt display Home/End", function()
		open(string.rep("abcd", 20), 4, 2)
		sci.send(c, 2025, 2)
		C.get("scintilla").event(c, st, { type = "key", key = iup.K_PGDN, mods = {} }, R)
		assert.equal(14, sci.send(c, 2008)); assert.equal(0, sci.send(c, 2152))
		C.get("scintilla").event(c, st, { type = "key", key = iup.K_DOWN, mods = {} }, R)
		assert.equal(18, sci.send(c, 2008)); assert.equal(1, sci.send(c, 2152))
		C.get("scintilla").event(c, st, { type = "key", key = iup.K_HOME, mods = { alt = true } }, R)
		assert.equal(16, sci.send(c, 2008))
		C.get("scintilla").event(c, st, { type = "key", key = iup.K_END, mods = { alt = true } }, R)
		assert.equal(20, sci.send(c, 2008))
	end)
end)
