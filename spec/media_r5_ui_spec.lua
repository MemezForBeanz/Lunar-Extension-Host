describe("round 5 media layout", function()
    local iup, R, old_path, old_raw
    before_each(function()
        old_path, old_raw = package.path, package.loaded.iupraw
        package.path = "extensions/media/?.lua;" .. old_path
        package.loaded.iupraw = require("core.imgui.native.iupraw")
        R = require("core.imgui.Runtime")
        R.init(require("core.imgui.backend.Null").new())
        iup = require("core.imgui.iup")
    end)
    after_each(function()
        package.path, package.loaded.iupraw = old_path, old_raw
    end)
    it("dismisses the entire feed surface and reports recovery", function()
        local notice = require("ui.reliability").new({iup=iup}, {origins={{name="Feed",status="failed",error="Offline"}}})
        assert.equals("Feed: Offline", notice.message)
        assert.equals("flatframe", iup.GetClassName(notice.widget))
        local row = iup.GetChild(notice.widget, 0)
        local rail = iup.GetChild(row, 0)
        local line = iup.GetChild(row, 1)
        assert.equals("3x", iup.GetAttribute(rail, "RASTERSIZE"))
        iup.GetChild(line, 2):flat_action()
        assert.equals("NO", iup.GetAttribute(notice.widget, "VISIBLE"))
        notice.setModel({})
        assert.is_nil(notice.message)
        iup.Destroy(notice.widget)
    end)
    it("opens the narrow drawer over its scrim and clears it on close", function()
        local page = require("core.ui.Kit").page(iup, {title="Media", main=iup.vbox{}, inspector={title="Selected",widget=iup.vbox{}}})
        local drawer = require("ui.drawer").new(iup, page)
        page:fit(1036)
        page:openInspector(true)
        drawer:fit(1036)
        assert.equals(page.inspector, iup.GetChild(page.inspectorOverlay, iup.GetChildCount(page.inspectorOverlay)-1))
        local scrim = iup.GetChild(page.inspectorOverlay, 1)
        assert.equals("YES", iup.GetAttribute(scrim, "VISIBLE"))
        assert.equals("YES", iup.GetAttribute(scrim, "_IUPLUNAR_OVERLAY"))
        page:openInspector(false)
        drawer:sync()
        assert.equals("NO", iup.GetAttribute(scrim, "VISIBLE"))
        iup.Destroy(page:widget())
    end)
    it("uses the live run icon for Sources search and stop", function()
        local api = require("ui.discover").new({iup=iup}, {providers={{id="archive",kind="archive",name="Archive"}}})
        api.page.mediaCaptureState("working")
        assert.equals("Stop", iup.GetAttribute(api.page.primary, "TITLE"))
        assert.equals("working", api.page.runIcon:state())
        api.page.mediaCaptureState("failed")
        assert.equals("Search / Browse", iup.GetAttribute(api.page.primary, "TITLE"))
        assert.equals("ready", api.page.runIcon:state())
        iup.Destroy(api.widget)
    end)
end)
