package.path = './extensions/media-server/?.lua;' .. package.path
local Web = require('libs.websources')
local cjson = require('cjson')
local function provider(id)
 for _, p in ipairs(Web.SITES) do if p.id == id then return p end end
end
describe('website source adapters', function()
 it('keeps fixed adapters on their own origin and rejects empty URLs', function()
  assert.is_nil(Web.request(provider('9anime'), '', 1, 'https://elsewhere.example/a'))
  assert.is_nil(Web.absolute('https://example.org/a', ''))
  assert.is_false(Web.web('https://name:password@example.org/a'))
  assert.equal('https://9anime.or.at/?s=space%20film', Web.request(provider('9anime'), 'space film', 1).url)
 end)
 it('reads title cards, deduplicates links, and flags series rather than episodes', function()
  local result = Web.parse([[<a href='/anime/space/'><img src='/cover.jpg' alt='Space'></a><a href='/anime/space/'>Space</a>]],
   'https://9anime.or.at/', provider('9anime'))
  assert.equal(1, #result.items)
  assert.equal('https://9anime.or.at/cover.jpg', result.items[1].poster_url)
  assert.is_true(result.items[1].is_series)
 end)
 it('requests the public episode API without executing page scripts', function()
  local result = Web.parse([[<meta property='og:title' content='Watch Space - 9anime'><section class='block_area-episodes' data-series='12'></section>]],
   'https://9anime.or.at/anime/space/', provider('9anime'), '', true)
  assert.equal('Space', result.title)
  assert.equal('https://9anime.or.at/wp-json/9animetv/v1/episodes/12?active=0', result.followup.url)
 end)
 it('turns episode API fragments into ordered episodes carrying their series and poster', function()
  local result = Web.parse(cjson.encode({pages=[[<a href='https://9anime.or.at/space-episode-4/' data-number='4'>4</a><a href='/space-episode-2/' data-number='2'>2</a>]]}),
   'https://9anime.or.at/wp-json/9animetv/v1/episodes/12?active=0', provider('9anime'), '', true,
   {title='Space',poster_url='https://images.example/space.jpg'})
  assert.equal(2, #result.items)
  assert.equal(2, result.items[1].episode)
  assert.equal('episode', result.items[1].kind)
  assert.equal('Space', result.items[1].show)
  assert.equal('https://images.example/space.jpg', result.items[1].poster_url)
 end)
 it('reads KissAnime series episodes and keeps unrelated suggestions out', function()
  local result = Web.parse([[<meta property='og:title' content='Space - Watch Online Free - KissAnime'><a href='/Anime/Space/Episode-031?id=1'>Episode 031</a><a href='/Anime/Other'>Other</a>]],
   'https://kissanime.tv.in/Anime/Space', provider('kissanime'), '', true)
  assert.equal(1, #result.items)
  assert.equal(31, result.items[1].episode)
  assert.equal('Space', result.items[1].show)
 end)
 it('resolves the ordinary public player request and encoded embed URL', function()
  assert.equal('https://9anime.or.at/ajax/episode/servers?id=959', Web.embed([[<iframe src=''></iframe><script>var tsEp={episodeId:959};</script>]], 'https://9anime.or.at/space-episode-54/'))
  local encoded = require('mime').b64('https://video.example/player')
  assert.equal('https://video.example/player', Web.embed(cjson.encode({html='<div data-embed="'..encoded..'"></div>'}), 'https://9anime.or.at/ajax/episode/servers?id=959'))
 end)
 it('reads direct video sources without treating empty player attributes as a stream', function()
  assert.equal('https://video.example/movie.mp4', Web.stream([[<video src=''><source src='/movie.mp4' type='video/mp4'></video>]], 'https://video.example/player'))
  assert.equal('https://video.example/player', Web.embed([[<iframe src=''></iframe><iframe src='https://video.example/player'></iframe>]], 'https://other.example/a'))
 end)
 it('does not mistake a player help message for an unavailable video', function()
  assert.is_falsy(Web.unavailable('<title>Space</title><p>If video not available, choose another server.</p>'))
  assert.is_truthy(Web.unavailable('<h1>Video Not Available</h1><p>Contact support.</p>'))
 end)
end)
