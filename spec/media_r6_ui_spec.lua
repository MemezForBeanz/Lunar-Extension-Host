describe("round 6 media details", function()
    local iup, old_path, old_raw
    before_each(function()
        old_path, old_raw = package.path, package.loaded.iupraw
        package.path = "extensions/media/?.lua;" .. old_path
        package.loaded.iupraw = require("core.imgui.native.iupraw")
        require("core.imgui.Runtime").init(require("core.imgui.backend.Null").new())
        iup = require("core.imgui.iup")
    end)
    after_each(function() package.path, package.loaded.iupraw = old_path, old_raw end)
    it("summarizes failures without repeating the recovery sentence", function()
        local notice = require("ui.reliability").new({iup=iup}, {origins={
            {name="Film feed",status="failed",error="It answered 503."},
            {name="TV feed",status="failed",error="Timed out."},
        }})
        assert.equals("2 sources unavailable", notice.summary)
        assert.equals("Film feed: It answered 503.", notice.message)
        notice.setModel({origins={{name="Film feed",status="failed"}}})
        assert.equals("1 source unavailable", notice.summary)
        notice.setModel({})
        assert.is_nil(notice.summary)
        iup.Destroy(notice.widget)
    end)
    it("does not reserve space for a missing source description", function()
        local api = require("ui.discover").new({iup=iup}, {providers={{id="archive",kind="archive",name="Archive"}}})
        local catalog = iup.GetChild(api.page.main, 1)
        local description = iup.GetChild(catalog, 0)
        assert.equals("NO", iup.GetAttribute(description, "VISIBLE"))
        api.capture("connected")
        assert.equals("NO", iup.GetAttribute(description, "VISIBLE"))
        iup.Destroy(api.widget)
    end)
    it("keeps the inspector close action unfilled", function()
        local page = require("core.ui.Kit").page(iup, {title="Media",main=iup.vbox{},inspector={title="Selected",widget=iup.vbox{}}})
        require("ui.drawer").new(iup,page)
        local header = iup.GetChild(iup.GetChild(page.inspector,0),0)
        assert.equals("link_btn", iup.GetAttribute(iup.GetChild(header,2),"THEMEROLE"))
        iup.Destroy(page:widget())
    end)
end)
