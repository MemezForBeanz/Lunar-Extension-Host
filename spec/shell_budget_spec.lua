local ShellBudget = require("core.ui.ShellBudget")

describe("shell height budget", function()
	it("reserves sibling bands and the gaps between all four bands", function()
		assert.equal(922, ShellBudget.cap(1000, { 40, 2, 30 }, 2, 4))
	end)
	it("floors the remaining height at 320", function()
		assert.equal(320, ShellBudget.cap(300, { 40, 2, 30 }, 2, 4))
		assert.equal(320, ShellBudget.cap(320, {}, 0, 1))
	end)
	it("treats absent measurements as zero, including holes", function()
		assert.equal(964, ShellBudget.cap(1000, { [3] = 30 }, 2, 4))
		assert.equal(994, ShellBudget.cap(1000, nil, 2, 4))
	end)
	it("does not reserve a gap for a single band", function()
		assert.equal(1000, ShellBudget.cap(1000, {}, 2, 1))
	end)
end)
