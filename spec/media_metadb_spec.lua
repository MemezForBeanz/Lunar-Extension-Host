package.path='./extensions/media/?.lua;'..package.path
local db=require('libs.metadb')
local Client=require('libs.metaclient')
local json=require('cjson')
describe('direct metadata providers',function()
 it('ships the same adapters inside both independent extensions',function()
  for _,name in ipairs({'metadb','metaclient','tmdb'}) do
   local a=assert(io.open('extensions/media/libs/'..name..'.lua','rb'));local b=assert(io.open('extensions/media-server/libs/'..name..'.lua','rb'))
   assert.equal(a:read('*a'),b:read('*a'));a:close();b:close()
  end
 end)
 it('keeps free providers and optional personal-token providers',function()
  assert.is_true(db.provider('tvmaze').keyless);assert.is_true(db.provider('jikan').keyless)
  assert.is_true(db.provider('cinemeta').keyless);assert.is_true(db.provider('kitsu').keyless)
  assert.is_true(db.provider('imdbot').experimental);assert.is_nil(db.provider('tmdb').keyless);assert.is_nil(db.provider('tvdb').keyless)
 end)
 it('uses only fixed origins and rejects arbitrary operations and ids',function()
  assert.is_nil(db.request('https://evil','search',{kind='movie',title='Film'}))
  assert.is_nil(db.request('tvmaze','search',{kind='movie',title='Film'}))
  assert.is_nil(db.request('cinemeta','details',{kind='movie'},'tt1/../../x'))
  assert.is_nil(db.request('kitsu','delete',{kind='show'},1))
  assert.is_truthy(db.request('cinemeta','search',{kind='movie'},'A&B'):find('A%26B',1,true))
 end)
 it('maps TVmaze summaries, posters and cast roles while tolerating null images',function()
  local f=assert(db.details('tvmaze','show',1,{id=1,name='Show',premiered='2020-01-02',summary='<p>A &amp; B.</p>',image={original='https://static.tvmaze.com/a.jpg'},_embedded={cast={{person={name='Actor',image=json.null},character={name='Role'}}}}}))
  assert.equal('A & B.\n',f.overview);assert.equal('Role',f.cast[1].role);assert.equal(2020,f.year);assert.is_truthy(f.poster_url)
 end)
 it('maps keyless movie descriptions, artwork and IMDb ids from Cinemeta',function()
  local f=assert(db.details('cinemeta','movie','tt0120338',{meta={id='tt0120338',name='Titanic',releaseInfo='1997',description='Voyage',poster='https://images.metahub.space/poster/small/tt0120338/img',background='https://images.metahub.space/background/medium/tt0120338/img',cast={'Actor'},imdbRating='8.0'}}))
  assert.equal('Voyage',f.overview);assert.equal(1997,f.year);assert.equal(8,f.rating);assert.same({'Actor'},f.people);assert.is_truthy(f.backdrop_url)
 end)
 it('filters anime movies from show results and normalizes rating scales',function()
  local kitsu={data={{id='1',attributes={canonicalTitle='Film',subtype='movie',averageRating='85',posterImage=json.null}},{id='2',attributes={canonicalTitle='Series',subtype='TV'}}}}
  local rows=assert(db.results('kitsu','movie',kitsu));assert.equal(1,#rows);assert.equal(8.5,rows[1].rating)
  assert.equal('Series',assert(db.results('kitsu','show',kitsu))[1].title)
  local anime=assert(db.details('jikan','show',1,{data={mal_id=1,title='Anime',type='TV',synopsis='Story',images={jpg={large_image_url='https://cdn.myanimelist.net/a.jpg'}},genres={{name='Drama'}},aired={prop={from={year=1998}}}}}))
  assert.equal(1998,anime.year);assert.equal('Drama',anime.genres[1]);assert.is_nil(db.details('jikan','movie',1,{data={mal_id=1,title='Anime',type='TV'}}))
 end)
 it('recognizes TVDB search ids without treating popularity as a rating',function()
  local rows=assert(db.results('tvdb','show',{data={{id='series-12',tvdb_id='12',name='Series',score=999}}}))
  assert.equal('12',rows[1].id);assert.is_nil(rows[1].rating)
 end)
 it('rejects unavailable or malformed unofficial lookup responses',function()
  assert.is_nil(db.results('imdbot','movie',{ok=false,error_message='SERVER_FAILURE_25'}))
  assert.is_nil(db.details('cinemeta','movie','tt1',{meta={id='tt2',name='Wrong'}}))
 end)
 it('rebuilds typed public facts and rejects image URLs outside provider CDNs',function()
  local f=assert(db.validateFacts({provider='cinemeta',external_id='tt1',title='Film',source_url='https://evil/',poster_url='https://127.0.0.1/secret',year={},rating=999,genres={'Drama',{}},token='must-not-persist'},'movie'))
  assert.is_nil(f.poster_url);assert.is_nil(f.token);assert.is_nil(f.year);assert.is_nil(f.rating);assert.same({'Drama'},f.genres);assert.equal('https://www.imdb.com/title/tt1',f.source_url)
 end)
end)
describe('bounded direct metadata client',function()
 it('requires no server or credential for public providers and caches repeated calls',function()
  local calls=0;local client=Client.new({http=function(req,done) calls=calls+1;assert.is_nil(req.headers.Authorization);done({ok=true,body='{"metas":[]}'}) end})
  client:search('cinemeta',{kind='movie',title='Film'},nil,function(rows) assert.same({},rows) end)
  client:search('cinemeta',{kind='movie',title='Film'},nil,function(rows) assert.same({},rows) end)
  assert.equal(1,calls)
 end)
 it('spaces every Jikan request and honors provider Retry-After',function()
  local now,calls=100,0;local client=Client.new({now=function() return now end,http=function(req,done) calls=calls+1;if calls==1 then done({ok=false,status=429,headers={['retry-after']='90'}}) else done({ok=true,body='{"data":[]}'}) end end})
  client:search('jikan',{kind='show',title='One'},nil,function(_,why,retry) assert.equal(90,retry);assert.is_truthy(why) end)
  client:search('jikan',{kind='show',title='Two'},nil,function() end)
  now=189;client:tick();assert.equal(1,calls);now=190;client:tick();assert.equal(2,calls)
 end)
 it('sends optional credentials only to the fixed provider origin',function()
  local req;local client=Client.new({get_secret=function(name) if name=='tmdb_token' then return 'private-token' end end,http=function(r,done) req=r;done({ok=true,body='{"results":[]}'}) end})
  client:search('tmdb',{kind='movie',title='Film'},nil,function() end)
  assert.equal('Bearer private-token',req.headers.Authorization);assert.is_truthy(req.url:match('^https://api%.themoviedb%.org/'));assert.is_nil(req.url:find('private-token',1,true))
  local encoded=json.encode(client:providers());assert.is_nil(encoded:find('private-token',1,true))
 end)
 it('logs into TVDB directly and never leaks the API key into a metadata request',function()
  local now,seen=100,{};local client=Client.new({now=function() return now end,get_secret=function(name) return ({tvdb_key='local-key',tvdb_pin='local-pin'})[name] end,http=function(r,done) seen[#seen+1]=r;if #seen==1 then assert.same({apikey='local-key',pin='local-pin'},json.decode(r.body));done({ok=true,body='{"data":{"token":"session-token"}}'}) else done({ok=true,body='{"data":[]}'}) end end})
  client:search('tvdb',{kind='show',title='Show'},nil,function() end);assert.equal(1,#seen)
  now=101;client:tick();assert.equal(2,#seen);assert.equal('Bearer session-token',seen[2].headers.Authorization);assert.is_nil(seen[2].body);assert.is_nil(seen[2].url:find('local-key',1,true))
 end)
 it('does not call a token provider before manual configuration and ignores late callbacks after close',function()
  local calls=0;local done;local client=Client.new({http=function(_,cb) calls=calls+1;done=cb end})
  client:search('tmdb',{kind='movie',title='Film'},nil,function(rows,why) assert.is_nil(rows);assert.is_truthy(why) end);assert.equal(0,calls)
  client:search('cinemeta',{kind='movie',title='Film'},nil,function() error('late callback') end);client:close();done({ok=true,body='{"metas":[]}'})
 end)
end)
