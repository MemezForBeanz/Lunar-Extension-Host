local Palette = require("core.ui.CommandPalette")
describe("command palette placement", function()
	it("opens above the bottom search field", function()
		local palette = Palette.new({ iup = {}, above = true, anchor = function() return 400, 900, 480 end })
		local x, y = palette:_place()
		assert.equal(320, x)
		assert.is_true(y < 600)
	end)
	it("keeps the existing anchor behavior for other callers", function()
		local palette = Palette.new({ iup = {}, anchor = function() return 400, 100, 480 end })
		local _, y = palette:_place()
		assert.equal(100, y)
	end)
	it("can fall back to the parent center before the toolbar is mapped", function()
		local palette = Palette.new({ iup = { CENTERPARENT = 123 }, above = true, anchor = function() end })
		local x, y = palette:_place()
		assert.equal(123, x)
		assert.equal(123, y)
	end)
end)
