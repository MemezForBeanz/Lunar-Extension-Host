-- IUP layout rules the shell depends on, each traced to iup_layout.c / iup_hbox.c /
-- iup_vbox.c / iup_fill.c and Lunar's patches 0005 and 0008.

local Null = require("core.imgui.backend.Null")

local iup, Layout, Element
local function setup()
	local Runtime = require("core.imgui.Runtime")
	Runtime.init(Null.new())
	Element = require("core.imgui.Element")
	Element.globals.DEFAULTFONT = "Segoe UI, -10" -- 5px chars, 13px lines in the Null backend
	iup = require("core.imgui.iup")
	Layout = require("core.imgui.Layout")
	require("core.imgui.Classes").define({ name = "leaf", children = 0, natural = function() return 40, 10 end })
end

local function leaf(attrs)
	return Element.new("leaf", attrs or {})
end
local function S(el) return Element.state(el) end
local function rect(el) local s = S(el); return { s.x, s.y, s.w, s.h } end

describe("imgui layout (IUP rules)", function()
	before_each(setup)

	it("a container expands only where its children can (EXPAND default YES & children)", function()
		local inner = iup.hbox({ leaf() })
		local outer = iup.vbox({ inner, leaf({ EXPAND = "HORIZONTAL" }) })
		Layout.natural(outer)
		local eh, ev = Layout.L.expand(inner)
		assert.is_false(eh)
		assert.is_false(ev)
		eh, ev = Layout.L.expand(outer)
		assert.is_true(eh)
		assert.is_false(ev)
	end)

	it("a box gives extra width only to children that expand that way", function()
		local a, b = leaf(), leaf({ EXPAND = "HORIZONTAL" })
		local dlg = iup.dialog({ iup.hbox({ a, b }) })
		Layout.run(dlg, 200, 100)
		assert.same({ 0, 0, 40, 10 }, rect(a))
		assert.same({ 40, 0, 160, 10 }, rect(b))
	end)

	it("does not give a horizontal-only child the box's height (the title bar bug)", function()
		local bar = iup.hbox({ leaf(), iup.fill({}), leaf(), EXPAND = "HORIZONTAL" })
		local body = iup.vbox({ leaf({ EXPAND = "YES" }) })
		local dlg = iup.dialog({ iup.vbox({ bar, body }) })
		Layout.run(dlg, 300, 400)
		assert.same({ 0, 0, 300, 10 }, rect(bar))
		assert.same({ 0, 10, 300, 390 }, rect(body))
	end)

	it("only uses IupFill's weak expand when nothing else in the box expands", function()
		local f = iup.fill({})
		local x = leaf({ EXPAND = "HORIZONTAL" })
		local dlg = iup.dialog({ iup.hbox({ leaf(), f, x }) })
		Layout.run(dlg, 200, 50)
		assert.equal(0, S(f).w)
		assert.equal(160, S(x).w)
		local f2 = iup.fill({})
		local last = leaf()
		local dlg2 = iup.dialog({ iup.hbox({ leaf(), f2, last }) })
		Layout.run(dlg2, 200, 50)
		assert.equal(120, S(f2).w)
		assert.equal(160, S(last).x)
	end)

	it("aligns children across the box", function()
		local a = leaf()
		-- an hbox's RASTERSIZE sets only its width, a vbox's only its height
		-- (iHboxSetRasterSizeAttrib, iVboxSetRasterSizeAttrib): the cross size comes from MINSIZE
		local dlg = iup.dialog({ iup.hbox({ a, ALIGNMENT = "ACENTER", MINSIZE = "x50" }) })
		Layout.run(dlg, 100, 50)
		assert.equal(20, S(a).y)
		local b = leaf()
		local dlg2 = iup.dialog({ iup.vbox({ b, ALIGNMENT = "ARIGHT", MINSIZE = "100x" }) })
		Layout.run(dlg2, 100, 50)
		assert.equal(60, S(b).x)
	end)

	it("uses MARGIN and GAP of the box itself only (patch 0005)", function()
		local a, b = leaf(), leaf()
		local inner = iup.hbox({ a, b })
		local dlg = iup.dialog({ iup.vbox({ inner, MARGIN = "10x5", GAP = "7" }) })
		Layout.run(dlg, 300, 300)
		assert.same({ 10, 5 }, { S(inner).x, S(inner).y })
		assert.equal(40, S(b).x - S(a).x) -- the inner hbox has no gap
	end)

	it("measures SIZE in quarter characters and eighth lines, RASTERSIZE in pixels", function()
		local a = leaf({ SIZE = "8x16" })
		Layout.natural(a)
		assert.same({ 10, 26 }, { S(a).nat_w, S(a).nat_h }) -- 8*5/4, 16*13/8
		local b = leaf({ RASTERSIZE = "x30" })
		Layout.natural(b)
		assert.same({ 40, 30 }, { S(b).nat_w, S(b).nat_h })
	end)

	it("lets the last of SIZE and RASTERSIZE win", function()
		local a = leaf({ SIZE = "8x8" })
		iup.SetAttribute(a, "RASTERSIZE", "70x20")
		Layout.natural(a)
		assert.same({ 70, 20 }, { S(a).nat_w, S(a).nat_h })
		iup.SetAttribute(a, "SIZE", "4x8")
		Layout.natural(a)
		assert.same({ 5, 13 }, { S(a).nat_w, S(a).nat_h })
	end)

	it("crops natural and expanded sizes with MINSIZE and MAXSIZE", function()
		local a = leaf({ EXPAND = "HORIZONTAL", MAXSIZE = "100x" })
		local dlg = iup.dialog({ iup.hbox({ a }) })
		Layout.run(dlg, 300, 20)
		assert.equal(100, S(a).w)
		local b = leaf({ MINSIZE = "60x30" })
		Layout.natural(b)
		assert.same({ 60, 30 }, { S(b).nat_w, S(b).nat_h })
	end)

	it("keeps a container at its natural size without SHRINK", function()
		local a, b = leaf({ RASTERSIZE = "100x10" }), leaf({ RASTERSIZE = "100x10" })
		local box = iup.hbox({ a, b })
		local dlg = iup.dialog({ box })
		Layout.run(dlg, 150, 20)
		assert.equal(200, S(box).w)
	end)

	it("gives width back in proportion to slack with SHRINK (patch 0008)", function()
		local fixed = leaf({ RASTERSIZE = "50x10" })
		local a = iup.hbox({ leaf({ RASTERSIZE = "100x10", EXPAND = "HORIZONTAL" }) })
		local b = iup.hbox({ leaf({ RASTERSIZE = "300x10", EXPAND = "HORIZONTAL" }) })
		local box = iup.hbox({ fixed, a, b })
		local dlg = iup.dialog({ box, SHRINK = "YES" })
		Layout.run(dlg, 250, 20)
		-- natural 450, deficit 200; the expanding children can spare 100 and 300 of it
		assert.equal(50, S(fixed).w)
		assert.equal(50, S(a).w)
		assert.equal(150, S(b).w)
		assert.equal(100, S(b).x)
	end)

	it("computes what a subtree cannot give up (iupLayoutMinContent)", function()
		local fixed = leaf({ RASTERSIZE = "30x10" })
		local stretchy = leaf({ EXPAND = "HORIZONTAL" })
		local box = iup.hbox({ fixed, stretchy, GAP = "4", MARGIN = "2x0" })
		Layout.natural(box)
		assert.equal(30 + 4 + 4, Layout.minContent(box, true))
		assert.equal(10, Layout.minContent(box, false))
	end)

	it("keeps FLOATING children out of the box and places them at POSITION", function()
		local a = leaf()
		local f = leaf({ FLOATING = "YES", POSITION = "5,6" })
		local box = iup.hbox({ a, f })
		local dlg = iup.dialog({ iup.vbox({ box, MARGIN = "10x10" }) })
		Layout.run(dlg, 200, 200)
		assert.equal(40, S(box).nat_w)
		-- POSITION is in the native parent's coordinates (iBaseSetPositionAttrib); the boxes
		-- are void, so it is measured from the dialog, not from the hbox at 10,10
		assert.same({ 5, 6, 40, 10 }, rect(f))
	end)

	it("lets hidden (VISIBLE=NO) children keep their space, as IUP does", function()
		local a, b = leaf({ VISIBLE = "NO" }), leaf()
		local dlg = iup.dialog({ iup.hbox({ a, b }) })
		Layout.run(dlg, 200, 50)
		assert.equal(40, S(b).x)
	end)

	it("inherits EXPAND from an enclosing container", function()
		local inner = iup.vbox({ leaf({ EXPAND = "YES" }) })
		local outer = iup.vbox({ inner, EXPAND = "HORIZONTAL" })
		Layout.natural(outer)
		local eh, ev = Layout.L.expand(inner)
		assert.is_true(eh)
		assert.is_false(ev)
	end)

	it("applies NORMALIZESIZE to every child but fills", function()
		local a, b = leaf({ RASTERSIZE = "30x10" }), leaf({ RASTERSIZE = "60x10" })
		local f = iup.fill({})
		local box = iup.vbox({ a, f, b, NORMALIZESIZE = "HORIZONTAL" })
		Layout.natural(box)
		assert.equal(60, S(a).nat_w)
		assert.equal(0, S(f).nat_w)
	end)

	it("shows a zbox's VALUEPOS child and keeps the others laid out", function()
		local a, b = leaf({ EXPAND = "YES" }), leaf({ EXPAND = "YES" })
		local z = iup.zbox({ a, b })
		local dlg = iup.dialog({ z })
		iup.SetAttribute(z, "VALUEPOS", "1")
		Layout.run(dlg, 120, 80)
		assert.equal("1", iup.GetAttribute(z, "VALUEPOS"))
		assert.equal(b, iup.GetAttributeHandle(z, "VALUE_HANDLE"))
		assert.same({ 0, 0, 120, 80 }, rect(a))
		assert.same({ b }, S(z).class.visibleChildren(z, S(z)))
	end)

	it("sizes a dialog from SIZE in screen fractions", function()
		local dlg = iup.dialog({ iup.vbox({}), SIZE = "HALFxHALF" })
		local w, h = Layout.natural(dlg)
		assert.same({ 960, 520 }, { w, h })
	end)
end)
