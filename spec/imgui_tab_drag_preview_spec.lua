local Null = require("core.imgui.backend.Null")
local R = require("core.imgui.Runtime")
local E = require("core.imgui.Element")
local Classes = require("core.imgui.Classes")
local iup = require("core.imgui.iup")
local Draw = require("core.imgui.Draw")
local motion = require("core.imgui.motion")
local Preview = require("core.imgui.TabDragPreview")
local Tabs = require("core.imgui.widgets.flattabs")

describe("ImGui live tab drag preview", function()
	local B, tabs, st, dc
	before_each(function()
		B = Null.new()
		R.init(B)
		motion.attach(nil); motion.setEnabled(true)
		tabs = iup.flattabs{ iup.vbox{}, iup.vbox{}, iup.vbox{},
			TABTITLE0 = "Alpha", TABTITLE1 = "Bravo", TABTITLE2 = "Charlie", TABSBREADTH = "48" }
		st = E.state(tabs)
		st.x, st.y, st.w, st.h = 20, 30, 400, 240
		dc = Draw.new(B)
		dc:begin(600, 400)
		Classes.get("flattabs").draw(tabs, st, dc)
	end)
	after_each(function() Preview.finish(); motion.setEnabled(true) end)

	it("slides neighbours during the drag while preserving the real tab order", function()
		local rects = Tabs.headerRects(tabs)
		local width = rects[1].w
		Preview.start(tabs, 0, 10, 8)
		Preview.update(tabs, 4, false, 200, 38)
		assert.equal(0, st.data.drag_source)
		assert.equal(-width, st.data.drag_offsets[1])
		assert.equal(-width, st.data.drag_offsets[2])
		Classes.get("flattabs").draw(tabs, st, dc)
		local cid = E.state(iup.GetChild(tabs, 1)).id
		local tween = st.data.motion["drag" .. cid]
		B.advance(0.05)
		Classes.get("flattabs").draw(tabs, st, dc)
		assert.is_true(tween.v < 0 and tween.v > -width)
		assert.equal("Alpha", iup.GetAttribute(tabs, "TABTITLE0"))
		assert.equal(3, iup.GetChildCount(tabs))
		assert.equal(1, #R.overlays())
		Preview.finish()
		assert.is_nil(st.data.drag_source)
		assert.equal(0, #R.overlays())
	end)

	it("opens a vertical insertion gap and keeps a combine target still", function()
		iup.SetAttribute(tabs, "TABTYPE", "LEFT")
		local rects = Tabs.headerRects(tabs)
		Preview.start(tabs, 2, 10, rects[3].y - st.y + 8)
		Preview.update(tabs, 1, false, 30, 38)
		assert.equal(rects[3].h, st.data.drag_offsets[0])
		assert.equal(rects[3].h, st.data.drag_offsets[1])
		Preview.update(tabs, nil, true, 30, 70)
		assert.is_nil(st.data.drag_offsets[0])
	end)

	it("does not lift a tab or displace neighbours with motion off", function()
		motion.setEnabled(false)
		Preview.start(tabs, 0, 10, 8)
		Preview.update(tabs, 4, false, 200, 38)
		assert.is_nil(st.data.drag_source)
		assert.is_nil(st.data.drag_offsets)
		assert.equal(0, #R.overlays())
	end)
end)
