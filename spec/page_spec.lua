local Kit = require("core.ui.Kit")
describe("declarative tool page", function()
    local iup
    before_each(function()
        iup = { DEFAULT = 0 }
        for _, kind in ipairs({ "scrollbox", "text", "flatlabel", "flatbutton", "vbox", "hbox", "fill", "split", "zbox", "flatframe" }) do
            iup[kind] = function(attrs) attrs.kind = kind; return attrs end
        end
        iup.SetAttribute = function(w, k, v) w[k] = v end
        iup.GetAttribute = function(w, k) return w[k] end
        iup.ResetAttribute = function(w, k) w[k] = nil end
        iup.Refresh = function() end
        iup.Detach = function() end
        iup.GetClassName = function(w) return w.kind end
        iup.GetChild = function(w, n) return w[n + 1] end
    end)
    it("keeps callbacks and the primary in the header when the mode changes", function()
        local hit
        local page = Kit.page(iup, { title = "Tests", primary = { title = "Run", action = function() hit = "run" end } })
        page.primary:flat_action()
        assert.equals("run", hit)
        page:setPrimary{ title = "Stop", action = function() hit = "stop" end }
        page.primary:flat_action()
        assert.equals("stop", hit)
        assert.equals(page.primary, page.header[#page.header])
    end)
    it("uses the pane width for config and inspector breakpoints", function()
        local page = Kit.page(iup, { config = { widget = iup.vbox{} }, main = iup.vbox{}, inspector = { widget = iup.vbox{} } })
        page:fit(1200)
        assert.equals("NO", page.config.FLOATING)
        assert.equals("YES", page.configure.FLOATING)
        page:fit(700)
        assert.equals("YES", page.config.FLOATING)
        assert.equals("NO", page.configure.FLOATING)
        page.configure:flat_action()
        assert.equals("NO", page.config.FLOATING)
        page:openInspector(true)
        assert.equals("120", page.inspectorSplit.VALUE)
        page:openInspector(false)
        assert.equals("1000", page.inspectorSplit.VALUE)
    end)
    it("folds secondary actions and retains the full state as a tooltip", function()
        local page = Kit.page(iup, { primary={title="Parse"}, secondary={{title="Browse"},{title="New parse"}} })
        page:fit(700)
        assert.equals("YES", page.secondary[1].FLOATING)
        assert.equals("NO", page.overflow.FLOATING)
        assert.equals("NO", page.primary.FLOATING)
        page:setState("info", "A long state sentence")
        assert.equals("A long state sentence", page.stateLine.TIP)
        page:setRunState("working")
        assert.equals("Stop", page.primary.TITLE)
        page:setRunState("ready")
        assert.equals("Parse", page.primary.TITLE)
    end)
    it("overlays narrow details without hiding the subject on ImGui", function()
        iup._IMGUI = true
        local page = Kit.page(iup, {main=iup.vbox{}, inspector={title="Details",widget=iup.vbox{}}})
        page:fit(700)
        page:openInspector(true)
        assert.equals("1000", page.inspectorSplit.VALUE)
        assert.equals("NO", page.mainHost.FLOATING)
        assert.equals("YES", page.inspector.FLOATING)
        assert.equals("YES", page.inspector.VISIBLE)
        page:openInspector(false)
        assert.equals("NO", page.inspector.VISIBLE)
    end)
    it("keeps the summary visible and opens failures, closes successes", function()
        local page = Kit.page(iup, { dock = { widget = iup.vbox{}, summary = "No output" } })
        assert.is_false(page.dockOpen)
        page:setDockSummary("error", "Build failed", function() end)
        assert.is_true(page.dockOpen)
        assert.equals("Build failed", page.dockSummary.TITLE)
        assert.equals("NO", page.dockAction.FLOATING)
        page:setDockSummary("success", "Build complete")
        assert.is_false(page.dockOpen)
        assert.equals("IGNORE", page.dockContent.FLOATING)
    end)
    it("stages an operation without showing results from the previous run", function()
        iup.Append = function(parent, child) table.insert(parent, child) end
        local page = Kit.page(iup, {title="Scan Chain", main=iup.vbox{ iup.flatlabel{TITLE="Previous successful result"} }, primary={title="Parse"}})
        local fixtures = dofile("scripts/ui_fixtures.lua")
        fixtures.tool_state(page, "working")
        assert.equals("YES", page.main.FLOATING)
        assert.equals("NO", page.capturePlaceholder.FLOATING)
        assert.equals("Stop", page.primary.TITLE)
        fixtures.tool_state(page, "failed")
        assert.is_true(page.dockOpen)
        assert.matches("incomplete device record", page.dockContent[1].VALUE, 1, true)
        assert.equals("YES", page.main.FLOATING)
        assert.equals("Retry", page.primary.TITLE)
        assert.equals("Results will appear here after a completed run.", page.capturePlaceholder.TITLE)
        assert.is_nil(page.stateLine.TITLE:find("fixture", 1, true))
    end)
    it("bounds remembered widths and saves dragged geometry per page", function()
        local values = { ["page.Test.config"] = 999 }
        local settings = { get = function(_, k) return values[k] end, set = function(_, k, v) values[k] = v end, save = function() end }
        local page = Kit.page(iup, { title = "Test", settings = settings, config = { widget = iup.vbox{} } })
        assert.equals(360, page.configSize)
        page:fit(1200)
        page.configSplit.VALUE = "250"
        page.configSplit:valuechanged_cb()
        assert.equals(300, values["page.Test.config"])
    end)
    it("keeps extra secondary actions available in overflow", function()
        local page = Kit.page(iup, { secondary = { { title = "One" }, { title = "Two" }, { title = "Three" } } })
        assert.equals(2, #page.secondary)
        assert.equals("NO", page.overflow.FLOATING)
        assert.equals("Three", page.secondarySpecs[3].title)
    end)
end)

describe("tool page header geometry", function()
    it("keeps a late failure dock readable beside a tall configuration form", function()
        local iup = require("core.lui.test").boot({})
        local fields = {EXPAND="YES"}
        for n=1,20 do fields[n]=iup.flatlabel{TITLE="Configuration",RASTERSIZE="200x32"} end
        local page = Kit.page(iup,{title="Log Parser",config={widget=iup.vbox(fields)}})
        page:ensureDock{widget=iup.text{MULTILINE="YES",EXPAND="YES"}}
        page:setDockSummary("error","Access denied")
        page:fit(1036,586)
        require("core.imgui.Layout").run(page.root,1036,586)
        assert.is_true(require("core.imgui.Element").state(page.dockContent).h >= 140)
    end)
    it("gives a short pane to readable output and restores configuration on close", function()
        local iup = require("core.lui.test").boot({})
        local Layout = require("core.imgui.Layout")
        local Element = require("core.imgui.Element")
        local text = iup.text{MULTILINE="YES", EXPAND="YES"}
        local page = Kit.page(iup,{config={title="Sections",widget=iup.vbox{}},dock={widget=text}})
        page:openDock(true)
        page:fit(700,320)
        Layout.run(page.root,700,320)
        assert.equal("IGNORE",iup.GetAttribute(page.body,"FLOATING"))
        assert.is_true(Element.state(text).h >= 120)
        assert.equal("outputlog",iup.GetAttribute(text,"THEMEROLE"))
        assert.equal("IBM Plex Mono, 10",iup.GetAttribute(text,"FONT"))
        assert.equal("NO",iup.GetAttribute(text,"SCROLLBAR"))
        assert.equal("well",iup.GetAttribute(page.dockContent,"THEMEROLE"))
        assert.equal("flatscrollbox",iup.GetClassName(iup.GetChild(page.dockContent,0)))
        page:openDock(false)
        assert.equal("NO",iup.GetAttribute(page.body,"FLOATING"))
    end)
    it("lets an automatic failure dock give way so the work keeps its minimum", function()
        local iup = require("core.lui.test").boot({})
        local Layout = require("core.imgui.Layout")
        local Element = require("core.imgui.Element")
        local P = require("core.lib.CarbonLayout").PAGE
        local list = iup.vbox{EXPAND="YES"}
        local page = Kit.page(iup,{title="Build Queue",bodyMin=320,toolbar=iup.hbox{},config={title="Catalog",widget=list},
            dock={widget=iup.text{MULTILINE="YES",EXPAND="YES"}}})
        page:setDockSummary("error","Build stopped on error",function() end)
        page:fit(1036,600)
        Layout.run(page.root,1036,600)
        assert.is_true(page.dockOpen)
        assert.is_false(page.renderedDockOpen)
        assert.equal("Show output",iup.GetAttribute(page.dockToggle,"TITLE"))
        assert.is_true(Element.state(page.body).h >= 320)
        -- the summary and its action stay on screen
        assert.equal("NO",iup.GetAttribute(page.dockAction,"FLOATING"))
        -- a taller pane has room again: the failure output opens by itself
        page:fit(1036,1000)
        Layout.run(page.root,1036,1000)
        assert.is_true(page.renderedDockOpen)
        assert.is_true(Element.state(page.dockContent).h >= P.dock_min - P.control)
        assert.is_true(Element.state(page.body).h >= 320)
    end)
    it("opens a dock the user asks for even where it had given way", function()
        local iup = require("core.lui.test").boot({})
        local Layout = require("core.imgui.Layout")
        local Element = require("core.imgui.Element")
        local page = Kit.page(iup,{bodyMin=320,config={widget=iup.vbox{EXPAND="YES"}},dock={widget=iup.text{MULTILINE="YES",EXPAND="YES"}}})
        page:fit(1036,560)
        page:setDockSummary("error","Failed",function() end)
        assert.is_false(page.renderedDockOpen)
        page.dockToggle:flat_action()
        Layout.run(page.root,1036,560)
        assert.is_true(page.renderedDockOpen)
        assert.equal("NO",iup.GetAttribute(page.body,"FLOATING"))
        assert.is_true(Element.state(page.dockContent).h >= 100)
        page.dockToggle:flat_action()
        assert.is_false(page.renderedDockOpen)
        assert.is_false(page.dockOpen)
        -- Open error forces the output open as well
        page:setDockSummary("error","Failed",function() end)
        page.dockAction:flat_action()
        assert.is_true(page.renderedDockOpen)
    end)
    it("shrinks the dock before it gives way", function()
        local iup = require("core.lui.test").boot({})
        local Layout = require("core.imgui.Layout")
        local Element = require("core.imgui.Element")
        local P = require("core.lib.CarbonLayout").PAGE
        local page = Kit.page(iup,{config={widget=iup.vbox{EXPAND="YES"}},dock={widget=iup.text{MULTILINE="YES",EXPAND="YES"}}})
        page:setDockSummary("error","Failed")
        local height = P.padding*2 + P.header + P.gutter + P.body_min + P.dock - 40
        page:fit(1036,height)
        Layout.run(page.root,1036,height)
        assert.is_true(page.renderedDockOpen)
        assert.is_true(Element.state(page.body).h >= P.body_min - 8)
    end)
    it("leaves no bar where a closed column was", function()
        local iup = require("core.lui.test").boot({})
        local page = Kit.page(iup,{config={widget=iup.vbox{}},main=iup.vbox{},inspector={title="Details",widget=iup.vbox{}}})
        page:fit(1400)
        assert.equal("0",iup.GetAttribute(page.inspectorSplit,"BARSIZE"))
        assert.is_true(tonumber(iup.GetAttribute(page.configSplit,"BARSIZE")) > 0)
        page:openInspector(true)
        assert.is_true(tonumber(iup.GetAttribute(page.inspectorSplit,"BARSIZE")) > 0)
        page:fit(700)
        assert.equal("0",iup.GetAttribute(page.configSplit,"BARSIZE"))
    end)
    it("gives every dock the same well and themes a late one", function()
        local iup = require("core.lui.test").boot({})
        local Reactor = require("core.ui.ThemeReactor")
        local themed = {}
        local old = Reactor.themeManager
        Reactor.themeManager = function() return { themeWidget = function(_, w) themed[#themed+1] = w end } end
        local ok, err = pcall(function()
            local frame = iup.flatframe{iup.vbox{}, THEMEROLE="well"}
            local declared = Kit.page(iup,{dock={widget=frame}})
            assert.equal(frame, declared.dockContent)
            local late = Kit.page(iup,{title="Log Parser",config={widget=iup.vbox{}}})
            late:ensureDock{widget=iup.text{MULTILINE="YES"}}
            assert.equal("well", iup.GetAttribute(late.dockContent,"THEMEROLE"))
            assert.equal(late.dockHost, themed[1])
            assert.equal(iup.GetAttribute(declared.dockAction,"THEMEROLE"), iup.GetAttribute(late.dockAction,"THEMEROLE"))
        end)
        Reactor.themeManager = old
        assert(ok, err)
    end)
    it("pins native and grouped primaries to the page padding at every pane width", function()
        local iup = require("core.lui.test").boot({})
        local Layout = require("core.imgui.Layout")
        local Element = require("core.imgui.Element")
        for _, grouped in ipairs({ false, true }) do
            local primary = grouped and { widget = iup.hbox{ iup.flatbutton{TITLE="Build"} } } or { title="Run" }
            local page = Kit.page(iup, {title="Build Queue", primary=primary, secondary={{title="Browse"}}})
            for _, width in ipairs({ 560, 700, 1036, 1872 }) do
                page:fit(width)
                Layout.run(page.root, width, 800)
                local action = Element.state(page.primary)
                assert.equal(width - require("core.lib.CarbonLayout").PAGE.padding, action.x + action.w)
            end
        end
    end)
end)
