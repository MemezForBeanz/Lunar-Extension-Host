local sqlite = require("core.lib.sqlite")
local ffi = require("ffi")
local platform = require("core.platform")

describe("core.lib.sqlite", function()
	if not sqlite.available then
		pending(sqlite.unavailable_reason)
		return
	end
	local db, path, other
	before_each(function()
		path = platform.path:join(platform.temp_dir(), "lunar_sqlite_" .. os.time() .. "_" .. math.random(1e9))
		os.remove(path)
		db = assert(sqlite.open(path))
	end)
	after_each(function()
		if other then other:close(); other = nil end
		if db then db:close() end
		for _, suffix in ipairs({ "", "-wal", "-shm", "-journal" }) do os.remove(path .. suffix) end
	end)
	local function row(sql)
		local stmt = assert(db:prepare(sql))
		local value = assert(stmt:step())
		assert.is_true(stmt:finalize())
		return value
	end
	it("opens with WAL, FULL synchronous, foreign keys and zero busy wait", function()
		assert.are.equal("wal", row("PRAGMA journal_mode").journal_mode)
		assert.are.equal(2, row("PRAGMA synchronous").synchronous)
		assert.are.equal(1, row("PRAGMA foreign_keys").foreign_keys)
		assert.are.equal(0, row("PRAGMA busy_timeout").timeout)
	end)
	it("binds copied text, numbers, booleans and NULL; resets and finalizes", function()
		local stmt = assert(db:prepare("SELECT ? AS text, ? AS number, ? AS flag, ? AS nullable"))
		assert(stmt:bind(1, "a\0b")); assert(stmt:bind(2, 42)); assert(stmt:bind(3, true)); assert(stmt:bind(4, sqlite.NULL))
		collectgarbage()
		assert.are.same({ text = "a\0b", number = 42, flag = 1, nullable = sqlite.NULL }, stmt:step())
		assert.is_false(stmt:step()); assert.is_false(stmt:step())
		assert(stmt:reset())
		assert.are.equal(sqlite.NULL, stmt:step().text)
		assert(stmt:finalize()); assert(stmt:finalize())
		assert.is_nil((stmt:step()))
	end)
	it("preserves int64 values outside Lua number precision", function()
		local stmt = assert(db:prepare("SELECT ? AS n"))
		local n = ffi.new("int64_t", 9007199254740991) + 2
		assert(stmt:bind(1, n))
		assert.is_true(stmt:step().n == n)
	end)
	it("returns nil,error for invalid SQL, bindings and closed handles", function()
		local ok, err = db:exec("not SQL")
		assert.is_nil(ok); assert.is_string(err)
		assert.is_nil((db:prepare("SELECT 1; SELECT 2")))
		local stmt = assert(db:prepare("SELECT ?"))
		assert.is_nil((stmt:bind(0, 1))); assert.is_nil((stmt:bind(1, {})))
		assert(db:close()); assert(db:close())
		assert.is_nil((stmt:step())); assert.is_nil((db:exec("SELECT 1")))
	end)
	it("commits and persists successful transactions", function()
		assert(db:exec("CREATE TABLE t(n INTEGER)"))
		assert(db:transaction(function(d) return d:exec("INSERT INTO t VALUES (7)") end))
		assert(db:close()); db = assert(sqlite.open(path))
		assert.are.equal(7, row("SELECT n FROM t").n)
	end)
	it("rolls back exceptions, returned errors and yields", function()
		assert(db:exec("CREATE TABLE t(n)"))
		for _, abort in ipairs({ function() error("oops") end,
			function() return nil, "oops" end, function() coroutine.yield() end }) do
			local ok, err = db:transaction(function(d)
				assert(d:exec("INSERT INTO t VALUES (1)"))
				return abort()
			end)
			assert.is_nil(ok); assert.is_string(err)
			assert.are.equal(0, row("SELECT count(*) AS n FROM t").n)
		end
	end)
	it("rejects nesting and closing a transaction", function()
		assert(db:transaction(function(d)
			assert.is_nil((d:transaction(function() end)))
			assert.is_nil((d:close()))
		end))
	end)
	it("migrates atomically, skips applied versions, refuses downgrades", function()
		assert(db:migrate(1, function(d, old)
			assert.are.equal(0, old)
			return d:exec("CREATE TABLE t(n)")
		end))
		assert(db:migrate(1, function() error("must not run") end))
		assert.is_nil((db:migrate(0, function() end)))
		assert.is_nil((db:migrate(2, function(d)
			assert(d:exec("ALTER TABLE t ADD COLUMN x"))
			return nil, "abort"
		end)))
		assert.are.equal(1, row("PRAGMA user_version").user_version)
		assert.is_nil((db:prepare("SELECT x FROM t")))
	end)
	it("returns busy immediately and enforces foreign keys", function()
		assert(db:exec("CREATE TABLE parent(id PRIMARY KEY); CREATE TABLE child(id REFERENCES parent(id))"))
		assert.is_nil((db:exec("INSERT INTO child VALUES (1)")))
		other = assert(sqlite.open(path))
		assert(db:exec("BEGIN IMMEDIATE"))
		local ok, err = other:exec("INSERT INTO parent VALUES (1)")
		assert.is_nil(ok); assert.matches("locked", err)
		assert(db:exec("ROLLBACK"))
	end)
end)
