"""Generate src/lua/core/imgui/cimgui_cdef.lua, the LuaJIT ffi.cdef of vendor/cimgui/cimgui.h.

    python scripts/gen_cimgui_cdef.py [path-to-mingw-cpp]

Preprocesses cimgui.h with CIMGUI_DEFINE_ENUMS_AND_STRUCTS (full struct layouts, so FFI code can
read ImGuiIO, ImDrawList, ImFont fields) against stub system headers: LuaJIT's FFI already knows
the stdint types, size_t, bool and va_list.
"""
import os, re, subprocess, sys, tempfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cpp = sys.argv[1] if len(sys.argv) > 1 else r"C:\msys64\mingw64\bin\cpp.exe"
tmp = tempfile.mkdtemp()
stubs = os.path.join(tmp, "stubs")
os.makedirs(stubs)
for name, text in {
    "stdio.h": "typedef struct _iobuf FILE;\n",
    "stdint.h": "", "stdarg.h": "", "stdbool.h": "", "stddef.h": "",
}.items():
    with open(os.path.join(stubs, name), "w") as f:
        f.write(text)
src = os.path.join(tmp, "wrap.h")
with open(src, "w") as f:
    f.write('#define CIMGUI_DEFINE_ENUMS_AND_STRUCTS\n#define CIMGUI_NO_EXPORT\n#include "cimgui.h"\n')
out = subprocess.check_output([cpp, "-P", "-nostdinc", "-undef", "-D_WIN32", "-I", stubs,
                               "-I", os.path.join(root, "vendor", "cimgui"), src], text=True)
lines = []
for line in out.splitlines():
    line = line.rstrip()
    if not line.strip():
        continue
    line = re.sub(r"^\s*extern\s+", "", line)
    lines.append(line)
body = "\n".join(lines)
if "]]" in body:
    raise SystemExit("cdef contains ]]")
dst = os.path.join(root, "src", "lua", "core", "imgui", "cimgui_cdef.lua")
with open(dst, "w", newline="\n") as f:
    f.write("-- Generated by scripts/gen_cimgui_cdef.py from vendor/cimgui/cimgui.h. Do not edit.\n")
    f.write("-- The C API of Dear ImGui as LuaJIT FFI declarations; core.imgui.cimgui loads it.\n")
    f.write("return [==[\n" + body + "\n]==]\n")
print(dst, len(lines), "lines")
