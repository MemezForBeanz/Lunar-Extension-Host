#!/usr/bin/env python3
"""embed_lua.py - Embeds Lua scripts into a C header for static linking.

Usage:
  embed_lua.py <main.lua> <output.h> [--scan BASE_DIR PATH ...] [--preload NAME FILE ...]

When invoked with only the first two arguments, generates a header containing
just the main script (backward compatible). With --scan and/or --preload,
also generates a preload_lua_modules() function that registers embedded Lua
modules into package.preload so require() finds them without filesystem access.

Options:
  --scan BASE_DIR PATH    Scan PATH (file or directory) for .lua files.
                          Module names are computed relative to BASE_DIR,
                          with path separators replaced by dots and .lua stripped.
  --preload NAME FILE     Embed FILE with the explicit module NAME.

Examples:
  embed_lua.py src/main.lua src/lua_bundle.h
  embed_lua.py src/main.lua src/lua_bundle.h \\
    --scan src src/scanner.lua \\
    --scan src src/lualibs \\
    --preload middleclass vendor/luarocks-tree/share/lua/5.1/middleclass.lua
"""
import os
import sys
import re


def escape_c_string(content: str) -> str:
    """Escape a string for inclusion in a C string literal.

    `?` becomes `\\?` so a Lua pattern like `%??(` can't form a C trigraph.
    """
    return (content
        .replace('\\', '\\\\')
        .replace('"',  '\\"')
        .replace('?',  '\\?')
        .replace('\n', '\\n"\n"'))


def safe_c_ident(module_name: str) -> str:
    """Convert a Lua module name (e.g. 'lualibs.ui.QueuePanel') to a valid C identifier."""
    return "lua_mod_" + re.sub(r'[^A-Za-z0-9_]', '_', module_name)


def collect_lua_files(base_dir: str, scan_path: str):
    """Yield (module_name, file_path) pairs for .lua files under scan_path."""
    base_dir = os.path.normpath(base_dir)
    scan_path = os.path.normpath(scan_path)

    if os.path.isfile(scan_path):
        if scan_path.endswith('.lua'):
            rel = os.path.relpath(scan_path, base_dir)
            mod_name = rel.replace(os.sep, '.').replace('/', '.')
            if mod_name.endswith('.lua'):
                mod_name = mod_name[:-4]
            yield (mod_name, scan_path)
    elif os.path.isdir(scan_path):
        for root, _dirs, files in os.walk(scan_path):
            for f in sorted(files):
                if f.endswith('.lua'):
                    full_path = os.path.join(root, f)
                    rel = os.path.relpath(full_path, base_dir)
                    mod_name = rel.replace(os.sep, '.').replace('/', '.')
                    if mod_name.endswith('.lua'):
                        mod_name = mod_name[:-4]
                    yield (mod_name, full_path)


def parse_args(argv):
    """Parse command line arguments."""
    if len(argv) < 3:
        print("Usage: embed_lua.py <main.lua> <output.h> [--scan BASE PATH] [--preload NAME FILE]",
              file=sys.stderr)
        sys.exit(1)

    main_lua = argv[1]
    output_h = argv[2]
    modules = []  # list of (module_name, file_path)

    i = 3
    while i < len(argv):
        if argv[i] == '--scan':
            if i + 2 >= len(argv):
                print("--scan requires BASE_DIR and PATH", file=sys.stderr)
                sys.exit(1)
            base_dir = argv[i + 1]
            scan_path = argv[i + 2]
            modules.extend(collect_lua_files(base_dir, scan_path))
            i += 3
        elif argv[i] == '--preload':
            if i + 2 >= len(argv):
                print("--preload requires NAME and FILE", file=sys.stderr)
                sys.exit(1)
            mod_name = argv[i + 1]
            mod_file = argv[i + 2]
            modules.append((mod_name, mod_file))
            i += 3
        else:
            print(f"Unknown argument: {argv[i]}", file=sys.stderr)
            sys.exit(1)

    return main_lua, output_h, modules


def main():
    main_lua, output_h, modules = parse_args(sys.argv)

    # Read and escape main script
    with open(main_lua, 'r', encoding='utf-8') as f:
        main_content = f.read()
    main_escaped = escape_c_string(main_content)

    # Read and escape each module
    mod_data = []
    for mod_name, mod_path in modules:
        with open(mod_path, 'r', encoding='utf-8') as f:
            content = f.read()
        mod_data.append({
            'name': mod_name,
            'path': mod_path,
            'c_ident': safe_c_ident(mod_name),
            'escaped': escape_c_string(content),
        })

    # Generate header
    with open(output_h, 'w', encoding='utf-8') as f:
        f.write('/* Auto-generated by embed_lua.py -- do not edit */\n')
        f.write('#ifndef LUA_BUNDLE_H\n')
        f.write('#define LUA_BUNDLE_H\n\n')

        # Main script
        f.write('/* Main application script */\n')
        f.write(f'static const char LUA_MAIN_SCRIPT[] =\n"{main_escaped}";\n\n')

        if mod_data:
            f.write('#include <lua.h>\n')
            f.write('#include <lauxlib.h>\n\n')

            # Each module as a named char array
            for m in mod_data:
                f.write(f'/* Embedded module: {m["name"]} ({os.path.basename(m["path"])}) */\n')
                f.write(f'static const char {m["c_ident"]}[] =\n"{m["escaped"]}";\n\n')

            # Module table
            f.write('typedef struct { const char *name; const char *code; int len; } lua_embedded_module;\n\n')
            f.write('static const lua_embedded_module LUA_MODULES[] = {\n')
            for m in mod_data:
                f.write(f'    {{"{m["name"]}", {m["c_ident"]}, sizeof({m["c_ident"]}) - 1}},\n')
            f.write('    {NULL, NULL, 0}\n')
            f.write('};\n\n')

            # Preload function
            f.write('/* Register all embedded Lua modules into package.preload */\n')
            f.write('static void preload_lua_modules(lua_State *L) {\n')
            f.write('    lua_getglobal(L, "package");\n')
            f.write('    lua_getfield(L, -1, "preload");\n')
            f.write('    for (int i = 0; LUA_MODULES[i].name != NULL; i++) {\n')
            f.write('        if (luaL_loadbuffer(L, LUA_MODULES[i].code,\n')
            f.write('                           (size_t)LUA_MODULES[i].len,\n')
            f.write('                           LUA_MODULES[i].name) == LUA_OK) {\n')
            f.write('            lua_setfield(L, -2, LUA_MODULES[i].name);\n')
            f.write('        }\n')
            f.write('    }\n')
            f.write('    lua_pop(L, 2);\n')
            f.write('}\n\n')

        f.write('#endif /* LUA_BUNDLE_H */\n')

    # Summary
    print(f"[embed_lua] {main_lua} -> {output_h}")
    if mod_data:
        print(f"[embed_lua] Embedded {len(mod_data)} module(s): {', '.join(m['name'] for m in mod_data)}")


if __name__ == '__main__':
    main()

