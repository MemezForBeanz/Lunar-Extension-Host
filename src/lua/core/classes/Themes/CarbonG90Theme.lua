    p.accentHover = p.buttonPrimaryHover
    p.accentPressed = p.buttonPrimaryActive
    p.accentBright = p.linkPrimary
    p.accentSoft = p.highlight
    p.error = p.supportError
    p.success = p.supportSuccess
    p.warning = p.supportWarning
    p.info = p.supportInfo
    p.surface = p.layer01
    p.surface2 = p.layerHover01
    p.border = p.borderSubtle01
    p.borderStrong = p.borderStrong01
    p.fieldBorder = p.borderStrong01
    p.listBg = p.layer01
    p.listText = p.textPrimary
    p.listSelText = p.textPrimary
    p.well = p.field01
    local br,bg,bb = p.bg:match("(%d+) (%d+) (%d+)")
    for name,value in pairs(tokens) do
        if type(value) == "string" then
            local r,g,b,a = value:match("rgba%((%d+),%s*(%d+),%s*(%d+),%s*([%d%.]+)%)")
            if not r then
                local percent
                r,g,b,percent = value:match("rgb%((%d+) (%d+) (%d+) / (%d+)%%%)")
                if percent then a = tonumber(percent)/100 end
            end
            if a then
                a = tonumber(a)
                p[name] = string.format("%d %d %d", math.floor(r*a+br*(1-a)+0.5), math.floor(g*a+bg*(1-a)+0.5), math.floor(b*a+bb*(1-a)+0.5))
            end
        end
    end
    p.warningText = carbon.rgb("#161616")
    Theme.initialize(self, { id = "carbon_g90", label = "Gray 90", family = "carbon", family_label = "Carbon", dark = true, palette = p })
end
